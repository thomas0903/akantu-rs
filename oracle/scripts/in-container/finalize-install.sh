#!/usr/bin/env bash
# SPDX-License-Identifier: LGPL-3.0-or-later
# Runs INSIDE the akantu-oracle:dev container (called by finalize-install.sh).
# Usage: finalize-install.sh <config> <scripts_sha>
# Makes /build/install-<config> usable for out-of-tree programs and verifies it:
#  1. writes share/akantu-oracle/oracle-flags.cmake (compile flags to reuse),
#     share/akantu-oracle/env.sh (PATH/LD_LIBRARY_PATH/PYTHONPATH/CMAKE_PREFIX_PATH)
#     and share/akantu-oracle/build-info.txt;
#  2. builds and runs oracle/consumer-smoke with find_package(Akantu);
#  3. imports the installed Python module and runs a tiny script;
#  4. on success writes /build/install-<config>/READY (scripts commit SHA).
set -euo pipefail

config="${1:?config}"
scripts_sha="${2:-unknown}"
build_dir="/build/${config}"
install_dir="/build/install-${config}"
share="${install_dir}/share/akantu-oracle"
log_dir="/build/logs/${config}"
[ -d "${install_dir}" ] || { echo "no install tree ${install_dir}" >&2; exit 2; }
mkdir -p "${share}" "${log_dir}"
rm -f "${install_dir}/READY"

cache() { sed -n "s/^$1:[A-Z]*=//p" "${build_dir}/CMakeCache.txt"; }
cxx_flags="$(cache CMAKE_CXX_FLAGS)"
build_type="$(cache CMAKE_BUILD_TYPE)"
bt_upper="$(echo "${build_type}" | tr '[:lower:]' '[:upper:]')"
bt_flags="$(cache "CMAKE_CXX_FLAGS_${bt_upper}")"
ref_sha="$(git -C /akantu-src rev-parse HEAD)"

# Python package. Upstream's install rules (python/CMakeLists.txt) are buggy:
# the module lands in lib/python./site-packages (empty Python version
# variables) and the package is nested (site-packages/akantu/akantu/*.py next
# to site-packages/akantu/py11_akantu*.so), so `import akantu` does not work
# from the install tree. Build a correct package view with relative symlinks
# in share/akantu-oracle/python/akantu (upstream files untouched).
py_so="$(find "${install_dir}/lib" -name 'py11_akantu*.so' | head -n1)"
[ -n "${py_so}" ] || { echo "py11_akantu not installed" >&2; exit 1; }
inst_pkg="$(dirname "${py_so}")"
py_root="${share}/python"
rm -rf "${py_root}" && mkdir -p "${py_root}/akantu"
ln -s "$(realpath --relative-to="${py_root}/akantu" "${py_so}")" "${py_root}/akantu/"
for f in "${inst_pkg}"/akantu/*.py; do
  ln -s "$(realpath --relative-to="${py_root}/akantu" "${f}")" "${py_root}/akantu/"
done

cat > "${share}/oracle-flags.cmake" <<EOF
# Generated by oracle/scripts/in-container/finalize-install.sh -- do not edit.
# Compile flags of the akantu-rs oracle build '${config}' (reference
# ${ref_sha}, scripts ${scripts_sha}). include() this file AFTER project() and
# BEFORE defining targets in any out-of-tree program linked against
# ${install_dir}: it reproduces the floating-point semantics and the Eigen
# ABI (EIGEN_DONT_VECTORIZE changes alignment) of the oracle library.
# See docs/DECISIONS.md D-031 and docs/ORACLE_BUILD.md.
set(AKANTU_ORACLE_CONFIG "${config}")
set(AKANTU_ORACLE_REFERENCE_SHA "${ref_sha}")
set(AKANTU_ORACLE_SCRIPTS_SHA "${scripts_sha}")
set(AKANTU_ORACLE_CXX_FLAGS "${cxx_flags}")
set(AKANTU_ORACLE_BUILD_TYPE "${build_type}")
set(AKANTU_ORACLE_BUILD_TYPE_CXX_FLAGS "${bt_flags}")
if(NOT CMAKE_BUILD_TYPE)
  set(CMAKE_BUILD_TYPE "${build_type}" CACHE STRING "" FORCE)
endif()
set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
string(APPEND CMAKE_CXX_FLAGS " \${AKANTU_ORACLE_CXX_FLAGS} -frounding-math")
# Use exactly the oracle's per-build-type flags for the oracle build type.
set(CMAKE_CXX_FLAGS_${bt_upper} "\${AKANTU_ORACLE_BUILD_TYPE_CXX_FLAGS}")
EOF

cat > "${share}/use-akantu-oracle.cmake" <<EOF
# Generated by finalize-install.sh -- one-stop include for out-of-tree CMake
# projects (after project()): imports Akantu from ${install_dir} and applies
# the oracle compile flags. Works around upstream AkantuConfig.cmake bugs
# (exported target needs Boost::graph and CGAL, which the config file does not
# import).
find_package(Boost REQUIRED COMPONENTS graph)
find_package(Eigen3 REQUIRED NO_MODULE)  # before CGAL (legacy FindEigen3 module)
find_package(CGAL REQUIRED)
find_package(Akantu REQUIRED CONFIG PATHS "${install_dir}/lib/cmake/Akantu" NO_DEFAULT_PATH)
include("${share}/oracle-flags.cmake")
EOF

cat > "${share}/env.sh" <<EOF
# Generated by finalize-install.sh -- source me:  . ${share}/env.sh
export AKANTU_ORACLE_INSTALL="${install_dir}"
export CMAKE_PREFIX_PATH="${install_dir}\${CMAKE_PREFIX_PATH:+:\${CMAKE_PREFIX_PATH}}"
export LD_LIBRARY_PATH="${install_dir}/lib\${LD_LIBRARY_PATH:+:\${LD_LIBRARY_PATH}}"
export PYTHONPATH="${py_root}\${PYTHONPATH:+:\${PYTHONPATH}}"
export OPENBLAS_NUM_THREADS=1 OMP_NUM_THREADS=1
EOF

{
  echo "config=${config}"
  echo "reference_sha=${ref_sha}"
  echo "scripts_sha=${scripts_sha}"
  echo "image_id=${ORACLE_IMAGE_ID:-unknown}"
  echo "arch=$(uname -m)"
  echo "compiler=$(g++ -dumpfullversion) ($(command -v g++))"
  echo "python_module_dir=${py_root}"
  grep -E '^(CMAKE_BUILD_TYPE|CMAKE_CXX_FLAGS|CMAKE_CXX_FLAGS_RELWITHDEBINFO|CMAKE_C_FLAGS|CMAKE_Fortran_FLAGS|AKANTU_EXTRA_CXX_FLAGS|CMAKE_CXX_COMPILER|AKANTU_IMPLICIT_SOLVER|MPIEXEC_MAX_NUMPROCS|CGAL_DIR):' \
    "${build_dir}/CMakeCache.txt"
  echo "packages_on=$(grep -E '^AKANTU_(USE_)?[A-Z_]+:BOOL=ON' "${build_dir}/CMakeCache.txt" | sed 's/:BOOL=ON//' | tr '\n' ' ')"
} > "${share}/build-info.txt"
cp /oracle/configs/common.cmake "/oracle/configs/${config}.cmake" "${share}/"

# --- 2. C++ consumer smoke test ---------------------------------------------
# shellcheck disable=SC1091
. "${share}/env.sh"
work="/build/consumer-smoke-${config}"
rm -rf "${work}" && mkdir -p "${work}/run"
cmake -S /oracle/consumer-smoke -B "${work}/build" -G Ninja \
  -DAKANTU_ORACLE_FLAGS_FILE="${share}/oracle-flags.cmake" \
  > "${work}/configure.log" 2>&1 || { cat "${work}/configure.log"; exit 1; }
ninja -C "${work}/build" -v > "${work}/build.log" 2>&1 || { cat "${work}/build.log"; exit 1; }
grep -E 'smoke.cc' "${work}/build.log" | head -n1 | sed 's/^/compile: /'
cp /oracle/consumer-smoke/material.dat "${work}/run/"
gmsh -2 -order 2 -o "${work}/run/square.msh" \
  /akantu-src/examples/c++/solid_mechanics_model/static/square.geo > /dev/null 2>&1
(cd "${work}/run" && "${work}/build/smoke") | tee "${share}/smoke-cxx.txt"

# --- 3. Python smoke test ---------------------------------------------------
(cd "${work}/run" && python3 - <<'EOF') | tee "${share}/smoke-python.txt"
import akantu as aka
import numpy as np
print("akantu module:", aka.__file__, "version:", aka.__version__)
aka.parseInput("material.dat")
mesh = aka.Mesh(2)
mesh.read("square.msh")
print("mesh: nodes", mesh.getNbNodes(), "sum(x) %.17g" % np.sum(mesh.getNodes()))
EOF

echo "${scripts_sha}" > "${install_dir}/READY"
echo "READY written: ${install_dir}/READY (${scripts_sha})"
