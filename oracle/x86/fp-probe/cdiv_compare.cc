// Part of akantu-rs (EPFL/LSMS Akantu port). Clean-room comparison
// (D-030: black-box only; only RESULTS of the compiled std::complex<double>
// division are observed, no library source is read, no library code is
// disassembled).
//
// Runs EXACTLY the input set of the clean-room experiment E25
// (oracle/probes/dense/complex_cleanroom/e25_special_random.cc: same RNG
// seed, same value mix, 2e7 random cases, then the 18^4 grid) and compares the
// division of this machine with
//   v5   : model_v5 (aarch64-derived, fused multiply-adds);
//   v5u  : model_v5 with every std::fma(x, y, z) replaced by x*y + z
//          (generated by sed from model_v1.h/model_v5.h, cdiv-compare.sh;
//          the x86 analysis's unfused model);
//   v6   : the later model_v6 (Baudin & Smith form 1) and model_v6_bs<2>,
//          when model_v6.h is available (-DHAVE_V6);
//   g<T> : v5u with the upscaling guard max(|a|,|b|), max(|c|,|d|) < 2^971 of
//          model_v5 replaced by "< T" (characterisation of the residual set);
// prints every residual case of v5u (and of v6 when it differs from v5u)
// with the properties that the review asked to state.
#include <vector>

#include "model_v5.h"
#include "model_v5u.h"
#if defined(HAVE_V6)
#include "model_v6.h"
#endif

namespace {

// model_v5's scaling with the 2^971 guard replaced by `guard`, on the
// unfused Smith core of model_v5u (model_v1u) and model_v5's Annex G
// recovery: g<guard>.
C scaled_unfused(double a, double b, double c, double d, double guard) {
  double ab = absmax(a, b), cd = absmax(c, d);
  if (cd >= 0x1.fffffffffffffp+1022) { a *= 0.5; b *= 0.5; c *= 0.5; d *= 0.5; }
  else if (cd < 0x1p-52) { a *= 0x1p52; b *= 0x1p52; c *= 0x1p52; d *= 0x1p52; }
  else if ((std::fabs(a) < 0x1p-1022 || std::fabs(b) < 0x1p-1022) && ab < guard && cd < guard) {
    a *= 0x1p52; b *= 0x1p52; c *= 0x1p52; d *= 0x1p52;
  }
  C z = model_v1u(a, b, c, d);
  double x = z.real(), y = z.imag();
  if (std::isnan(x) && std::isnan(y)) {
    if (c == 0.0 && d == 0.0 && (!std::isnan(a) || !std::isnan(b))) {
      x = std::copysign(INFINITY, c) * a;
      y = std::copysign(INFINITY, c) * b;
    } else if ((std::isinf(a) || std::isinf(b)) && std::isfinite(c) && std::isfinite(d)) {
      a = std::copysign(std::isinf(a) ? 1.0 : 0.0, a);
      b = std::copysign(std::isinf(b) ? 1.0 : 0.0, b);
      x = INFINITY * (a * c + b * d);
      y = INFINITY * (b * c - a * d);
    } else if ((std::isinf(c) || std::isinf(d)) && std::isfinite(a) && std::isfinite(b)) {
      c = std::copysign(std::isinf(c) ? 1.0 : 0.0, c);
      d = std::copysign(std::isinf(d) ? 1.0 : 0.0, d);
      x = 0.0 * (a * c + b * d);
      y = 0.0 * (b * c - a * d);
    }
  }
  return C(x, y);
}

bool eq(C w, C z) { return same(w.real(), z.real()) && same(w.imag(), z.imag()); }

const char * kind(double v) {
  double m = std::fabs(v);
  if (std::isnan(v)) return "nan";
  if (std::isinf(v)) return "inf";
  if (m == 0.0) return "zero";
  if (m < 0x1p-1022) return "subnormal";
  if (m == 0x1.fffffffffffffp+970) return "B";  // nextafter(2^971, 0)
  if (m == 0x1p971) return "2^971";
  return "normal";
}

struct Model {
  const char * name;
  long random = 0, grid = 0;
};

}  // namespace

int main() {
  const double guards[] = {0x1p971, 0x1.fffffffffffffp+970, 0x1p970};
  const char * guard_names[] = {"g<2^971 (= v5u)", "g<0x1.fffffffffffffp+970", "g<2^970"};
  Model v5{"v5 fused"}, v5u{"v5u unfused"}, v6a{"v6 BS1"}, v6b{"v6 BS2"};
  Model g[3] = {{guard_names[0]}, {guard_names[1]}, {guard_names[2]}};
  long v6_vs_v5u = 0, g0_vs_v5u = 0;
  long res_part_re = 0, res_part_im = 0, res_both = 0, res_sign_only = 0, res_B = 0, res_a_zero = 0;
  // --- E25's random set, verbatim generator --------------------------------
  std::vector<double> sp = {0.0, 0x1p-1074, 0x1p-1022, std::nextafter(0x1p-1022, 0.0), 0x1p-52,
                            std::nextafter(0x1p-52, 0.0), 1.0, 0x1p971, std::nextafter(0x1p971, 0.0), 0x1p972,
                            0x1.fffffffffffffp+1022, std::nextafter(0x1.fffffffffffffp+1022, 0.0),
                            0x1.fffffffffffffp+1023, INFINITY, NAN};
  Rng r{0xc0ffee25ULL};
  auto pick = [&]() {
    double v;
    switch (r.irange(0, 3)) {
      case 0: v = sp[r.irange(0, (int)sp.size() - 1)]; break;
      case 1: v = r.expo(-1074, 1023); break;
      case 2: v = r.anybits(); break;
      default: v = r.expo(-60, 60); break;
    }
    return (r.next() & 1) ? -v : v;
  };
  long total = 0;
  for (long k = 0; k < 20000000L; ++k) {
    double a = pick(), b = pick(), c = pick(), d = pick();
    C z = oracle_div(C(a, b), C(c, d));
    ++total;
    C w5 = model_v5(a, b, c, d), w5u = model_v5u(a, b, c, d);
    v5.random += !eq(w5, z);
    bool m5u = !eq(w5u, z);
    v5u.random += m5u;
#if defined(HAVE_V6)
    C w6a = model_v6(a, b, c, d), w6b = model_v6_bs<2>(a, b, c, d);
    v6a.random += !eq(w6a, z);
    v6b.random += !eq(w6b, z);
    v6_vs_v5u += !eq(w6a, w5u);
#endif
    for (int i = 0; i < 3; ++i) {
      C wg = scaled_unfused(a, b, c, d, guards[i]);
      bool m = !eq(wg, z);
      g[i].random += m;
      if (i == 0) g0_vs_v5u += !eq(wg, w5u);
      if (m && i > 0) {  // the guard variants' residuals bound the runtime's threshold
        std::printf("GRES %s ", guard_names[i]);
        print4("", a, b, c, d);
        std::printf(" | max(|c|,|d|) = %a max(|a|,|b|) = %a | oracle (%a, %a) model (%a, %a)\n", absmax(c, d),
                    absmax(a, b), z.real(), z.imag(), wg.real(), wg.imag());
      }
    }
    if (m5u) {
      bool dre = !same(w5u.real(), z.real()), dim = !same(w5u.imag(), z.imag());
      res_part_re += dre && !dim;
      res_part_im += dim && !dre;
      res_both += dre && dim;
      bool sign_only = (!dre || (w5u.real() == z.real())) && (!dim || (w5u.imag() == z.imag()));
      res_sign_only += sign_only;
      res_B += std::fabs(c) == 0x1.fffffffffffffp+970 || std::fabs(d) == 0x1.fffffffffffffp+970;
      res_a_zero += a == 0.0;
      print4("RES", a, b, c, d);
      std::printf(" | oracle (%a, %a) v5u (%a, %a) | kinds a=%s b=%s c=%s d=%s | differs %s%s\n", z.real(), z.imag(),
                  w5u.real(), w5u.imag(), kind(a), kind(b), kind(c), kind(d), dre ? "re" : "", dim ? "im" : "");
    }
  }
  // --- E25's grid ------------------------------------------------------------
  std::vector<double> base = {0.0, 0x1p-1074, 0x1p-1022, 1.0, 3.0, 0x1p1000, 0x1.fffffffffffffp+1023, INFINITY, NAN};
  std::vector<double> vals;
  for (double v : base) { vals.push_back(v); vals.push_back(-v); }
  long gt = 0;
  for (double a : vals) for (double b : vals) for (double c : vals) for (double d : vals) {
    C z = oracle_div(C(a, b), C(c, d));
    ++gt;
    v5.grid += !eq(model_v5(a, b, c, d), z);
    v5u.grid += !eq(model_v5u(a, b, c, d), z);
#if defined(HAVE_V6)
    v6a.grid += !eq(model_v6(a, b, c, d), z);
    v6b.grid += !eq(model_v6_bs<2>(a, b, c, d), z);
#endif
    for (int i = 0; i < 3; ++i) g[i].grid += !eq(scaled_unfused(a, b, c, d, guards[i]), z);
  }
  std::printf("SUMMARY E25 input set: random=%ld grid=%ld (machine division vs model; NaNs equal regardless of sign)\n",
              total, gt);
  std::vector<Model *> all = {&v5, &v5u};
#if defined(HAVE_V6)
  all.push_back(&v6a);
  all.push_back(&v6b);
#endif
  for (auto & m : g) all.push_back(&m);
  for (auto * m : all) std::printf("MODEL %-28s random_mismatches=%ld grid_mismatches=%ld\n", m->name, m->random, m->grid);
#if defined(HAVE_V6)
  std::printf("SELF v6 BS1 vs v5u differ on %ld random inputs\n", v6_vs_v5u);
#else
  std::printf("SELF v6 not available (model_v6.h absent)\n");
#endif
  std::printf("SELF g<2^971 vs v5u differ on %ld random inputs\n", g0_vs_v5u);
  std::printf("RESIDUALS v5u: %ld; real part only %ld, imaginary part only %ld, both %ld; sign-of-zero only %ld; "
              "|c| or |d| = 0x1.fffffffffffffp+970 in %ld; a = +-0 in %ld\n",
              v5u.random, res_part_re, res_part_im, res_both, res_sign_only, res_B, res_a_zero);
  // --- Guard threshold (E20-style bisection, black box) ---------------------
  // Family of the g<2^970 residual: a = -0, b = -0x1.534c5d091544p-101,
  // c = 2^-52, d = m. For each m the unfused model with the upscaling forced
  // on (U) and off (N) is compared with the machine division: the
  // threshold T is the smallest m at which the machine stops upscaling.
  auto verdict = [](double m) {  // +1 upscales, -1 does not, 0 indistinguishable / neither
    double a = -0.0, b = -0x1.534c5d091544p-101, c = 0x1p-52;
    C z = oracle_div(C(a, b), C(c, m));
    C up = scaled_unfused(a, b, c, m, INFINITY), no = scaled_unfused(a, b, c, m, 0.0);
    if (eq(up, no)) return 0;
    if (eq(z, up)) return 1;
    if (eq(z, no)) return -1;
    return 0;
  };
  double lo = 0x1.7c8efb3c30edp+970, hi = 0x1.fffffffffffffp+970;
  std::printf("GUARD family verdicts: lo %a -> %d, hi %a -> %d\n", lo, verdict(lo), hi, verdict(hi));
  if (verdict(lo) == 1 && verdict(hi) == -1) {
    std::uint64_t l = bits(lo), h = bits(hi);  // invariant: verdict(l) = +1, verdict(h) = -1
    bool clean = true;
    while (h - l > 1) {
      std::uint64_t mid = l + (h - l) / 2;
      int v = verdict(from_bits(mid));
      if (v == 1) l = mid;
      else if (v == -1) h = mid;
      else { clean = false; break; }
    }
    std::printf("GUARD %s: machine upscales at m = %a and not at m = %a (adjacent doubles: %s)\n",
                clean ? "bisection complete" : "bisection stopped on an indistinguishable m", from_bits(l), from_bits(h),
                h - l == 1 ? "yes" : "no");
    // Monotonicity spot check: 64 values on each side of the boundary.
    int bad = 0;
    for (int k = 1; k <= 64; ++k) {
      bad += verdict(from_bits(l - std::uint64_t(k) * 1000003ULL)) == -1;
      bad += verdict(from_bits(h + std::uint64_t(k) * 1000003ULL)) == 1;
    }
    std::printf("GUARD spot check: %d of 128 values on the wrong side\n", bad);
  }
}
