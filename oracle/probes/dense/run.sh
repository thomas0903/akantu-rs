#!/usr/bin/env bash
# SPDX-License-Identifier: LGPL-3.0-or-later
# Build and run the dense-algebra probe against the oracle install inside the
# oracle image, in three floating-point configurations, and write the
# fixtures. Run from the repository root:
#
#   oracle/probes/dense/run.sh
#
# Writes crates/akantu-linalg/tests/fixtures/dense/dense_strict.txt (the
# committed parity fixture) and dense_config_comparison.txt (how the two
# vectorised configurations differ from strict). Read-only mounts of the
# oracle build volume; nothing in the volume or the reference is modified.
set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")/../../scripts" && pwd)/oracle-env.sh"  # ORACLE_ENV_ARGS (D-050)
repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)
out="$repo/crates/akantu-linalg/tests/fixtures/dense"
mkdir -p "$out"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cp "$repo/oracle/probes/dense/probe.cc" "$work/"

docker run --rm ${ORACLE_ENV_ARGS[@]+"${ORACLE_ENV_ARGS[@]}"} --memory=4g \
  -v akantu-oracle-build:/build:ro \
  -v "$work:/work" -w /work akantu-oracle:dev bash -euc '
    common="-std=c++20 -O2 -DNDEBUG -I/usr/include/eigen3 -DOMPI_SKIP_MPICXX"
    build() { # name install extra-flags
      # D-050: the install'"'"'s Eigen cache-size pin (x86_64 only; empty on aarch64).
      pin=$(grep -o -e "-DEIGEN_NO_CPUID" -e "-DEIGEN_DEFAULT_L[123]_CACHE_SIZE=[0-9]*" \
              /build/$2/share/akantu-oracle/build-info.txt | sort -u | tr "\n" " " || true)
      g++ $common -I/build/$2/include/akantu -I/build/$2/include/akantu_iterators -I/build/$2/include $3 $pin probe.cc -o probe-$1 \
        -L/build/$2/lib -Wl,-rpath,/build/$2/lib -lakantu
      ./probe-$1 > $1.txt
    }
    # strict: the flags of the strict oracle library (primary golden data)
    build strict install-strict "-ffp-contract=off -DEIGEN_DONT_VECTORIZE"
    # contraction off but Eigen NEON kernels enabled (as requested in the brief)
    build neon install-default "-ffp-contract=off"
    # upstream default flags (contraction + NEON FMA kernels), = oracle "default"
    build default install-default ""
    {
      echo "# generated by oracle/probes/dense/run.sh"
      echo "# image: $(cat /etc/debian_version 2>/dev/null) $(uname -m), g++ $(g++ -dumpfullversion)"
      echo "# eigen: $(grep -E "define EIGEN_(WORLD|MAJOR|MINOR)_VERSION" /usr/include/eigen3/Eigen/src/Core/util/Macros.h | awk "{print \$3}" | paste -sd.)"
      echo "# strict  = -O2 -DNDEBUG -ffp-contract=off -DEIGEN_DONT_VECTORIZE (install-strict)"
      echo "# neon    = -O2 -DNDEBUG -ffp-contract=off (install-default headers)"
      echo "# default = -O2 -DNDEBUG (install-default headers)"
      echo "# columns: config records records_identical_to_strict"
      for c in neon default; do
        tot=$(wc -l < $c.txt)
        same=$(paste -d"\n" strict.txt $c.txt | awk "NR%2==1{a=\$0;next}{if(a==\$0)s++}END{print s+0}")
        echo "$c $tot $same"
        echo "# per op (records differing from strict):"
        paste -d"\t" strict.txt $c.txt | awk -F"\t" "\$1!=\$2{split(\$1,f,\" \");k=f[1]\" \"f[2]\" \"f[3];d[k]++}END{for(k in d)print \"#   \" k, d[k]}" | sort
      done
    } > comparison.txt
  '
{
  echo "# Dense parity fixture (review AR-16). Generated by oracle/probes/dense/run.sh"
  echo "# from the REAL upstream code (Akantu aka_types.hh / aka_voigthelper.hh at"
  echo "# 35a851780d0b9471d258ed53a003ae98aaa95ea0, Eigen 3.4.0) built with the strict"
  echo "# oracle flags: g++ 14.2.0 -std=c++20 -O2 -DNDEBUG -ffp-contract=off -DEIGEN_DONT_VECTORIZE,"
  echo "# aarch64 (Debian trixie, image akantu-oracle:dev). Format: oracle/probes/dense/README.md"
  cat "$work/strict.txt"
} > "$out/dense_strict.txt"
cp "$work/comparison.txt" "$out/dense_config_comparison.txt"
wc -l "$out/dense_strict.txt"
cat "$out/dense_config_comparison.txt"
