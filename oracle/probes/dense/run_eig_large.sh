#!/usr/bin/env bash
# SPDX-License-Identifier: LGPL-3.0-or-later
# akantu-rs: build the
# dense probe (probe.cc) with the strict oracle flags inside the oracle image
# and run its --eig-large mode three times (D-035: identical fixed-seed
# runs), writing crates/akantu-linalg/tests/fixtures/dense/dense_eig_large_strict.txt
# (eig / eigh records, run-time sizes 13..48; format: README.md). The probe
# pins Eigen's cache sizes (D-050); OPENBLAS_CORETYPE=Haswell and one thread
# are passed as for every pinned probe. dense_strict.txt is not touched.
# Read-only mounts of the oracle build volume.
#
#   oracle/probes/dense/run_eig_large.sh
set -euo pipefail
repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)
out="$repo/crates/akantu-linalg/tests/fixtures/dense"
ORACLE_IMAGE="${ORACLE_IMAGE:-akantu-oracle:dev}"
ORACLE_VOLUME="${ORACLE_VOLUME:-akantu-oracle-build}"
mkdir -p "$out"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cp "$repo/oracle/probes/dense/probe.cc" "$work/"
image_id="$(docker image inspect --format '{{.Id}}' "$ORACLE_IMAGE")"
probes_commit="$(git -C "$repo" rev-parse HEAD 2>/dev/null || echo unknown)"
[ -z "$(git -C "$repo" status --porcelain -- oracle/probes/dense 2>/dev/null)" ] ||
  probes_commit="${probes_commit}+uncommitted-probe-changes"
docker run --rm --memory=4g --user "$(id -u):$(id -g)" -e HOME=/tmp \
  -e OPENBLAS_CORETYPE=Haswell -e OPENBLAS_NUM_THREADS=1 -e OMP_NUM_THREADS=1 \
  -v "$ORACLE_VOLUME:/build:ro" \
  -v "$work:/work" -w /work "$ORACLE_IMAGE" bash -euc '
    common="-std=c++20 -O2 -DNDEBUG -I/usr/include/eigen3 -DOMPI_SKIP_MPICXX"
    g++ $common -I/build/install-strict/include/akantu -I/build/install-strict/include/akantu_iterators \
      -I/build/install-strict/include -ffp-contract=off -DEIGEN_DONT_VECTORIZE probe.cc -o probe-strict \
      -L/build/install-strict/lib -Wl,-rpath,/build/install-strict/lib -lakantu
    for k in 1 2 3; do ./probe-strict --eig-large > run$k.txt 2> err$k.txt; done
    cmp run1.txt run2.txt && cmp run1.txt run3.txt
    cat err1.txt
    {
      echo "# image: $(cat /etc/debian_version 2>/dev/null) $(uname -m), g++ $(g++ -dumpfullversion)"
      echo "# eigen: $(grep -E "define EIGEN_(WORLD|MAJOR|MINOR)_VERSION" /usr/include/eigen3/Eigen/src/Core/util/Macros.h | awk "{print \$3}" | paste -sd.)"
    } > env.txt
  '
{
  echo "# Dense eigen-decomposition records for 13 <= n <= 48 (D-065)."
  echo "# Generated by oracle/probes/dense/run_eig_large.sh (probe.cc --eig-large) from the REAL upstream code"
  echo "# (Akantu aka_types.hh at 35a851780d0b9471d258ed53a003ae98aaa95ea0, Eigen 3.4.0) built with the strict oracle"
  echo "# flags -std=c++20 -O2 -DNDEBUG -ffp-contract=off -DEIGEN_DONT_VECTORIZE; Eigen cache sizes pinned"
  echo "# (setCpuCacheSizes(16384, 524288, 524288), D-050), OPENBLAS_CORETYPE=Haswell, 1 thread; three identical runs."
  echo "# oracle image $image_id, probe sources $probes_commit."
  sed 's/^/# /' "$work/env.txt"
  echo "# Format: oracle/probes/dense/README.md (eig records only)."
  cat "$work/run1.txt"
} > "$out/dense_eig_large_strict.txt"
wc -lc "$out/dense_eig_large_strict.txt"
