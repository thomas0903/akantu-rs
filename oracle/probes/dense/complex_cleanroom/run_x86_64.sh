# Clean-room black-box probes of std::complex<double> division on the x86_64
# oracle image (D-043; run on an x86_64 Linux host with the oracle image and its build
# volume, from the repository root). Writes into
# ${CDIV_X86_OUT:-oracle/probes/dense/complex_cleanroom/results_x86_64}/:
#   toolchain.txt, e1.txt (the 64 Smith variants of E1), e4_model_v5.txt and
#   e4_model_v6.txt (whole-range residuals of the fused and unfused models),
#   e28.txt (E27's mix and the dense range, models v5 / v6 both Baudin & Smith
#   forms), gen_fixture_stats.txt, and complex_div_cleanroom_x86_64.txt (the
#   fixture generator's records with this runtime's results; the Rust test
#   complex_div_cleanroom.rs checks ComplexDivision::Unfused against it).
# Only the RESULTS of the compiled division are observed; no library source
# is read and no compiled library code is disassembled or inspected.
set -euo pipefail
repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)
dir=oracle/probes/dense/complex_cleanroom
out="${CDIV_X86_OUT:-$repo/$dir/results_x86_64}"
mkdir -p "$out"
out=$(cd "$out" && pwd)
echo "oracle image $(docker image inspect --format '{{.Id}}' akantu-oracle:dev)" > "$out/image.txt"
docker run --rm --memory=2g --user "$(id -u):$(id -g)" -e HOME=/tmp \
  -v "$repo":/w:ro -v "$out":/out -w "/w/$dir" akantu-oracle:dev bash -euc '
  cxx="g++ -O2 -std=c++20 -ffp-contract=off"
  { g++ --version | head -1; echo "debian $(cat /etc/debian_version) $(uname -m)"; } > /out/toolchain.txt
  $cxx e1_smith_variants.cc -o /tmp/e1 && /tmp/e1 | sort -t= -k8 -n > /out/e1.txt
  $cxx -DMODEL=model_v5 -DMODEL_HEADER=model_v5.h e4_residual.cc -o /tmp/e4v5 && /tmp/e4v5 40000000 10 > /out/e4_model_v5.txt
  $cxx -DMODEL=model_v6 -DMODEL_HEADER=model_v6.h e4_residual.cc -o /tmp/e4v6 && /tmp/e4v6 40000000 10 > /out/e4_model_v6.txt
  $cxx e28_unfused.cc -o /tmp/e28 && /tmp/e28 7000000 > /out/e28.txt
  $cxx gen_fixture.cc -o /tmp/gen && /tmp/gen > /tmp/fixture.txt 2> /out/gen_fixture_stats.txt
  {
    echo "# Clean-room complex division fixture, x86_64 runtime (D-043). Generated by"
    echo "# oracle/probes/dense/complex_cleanroom/run_x86_64.sh from black-box runs of std::complex<double>"
    echo "# division in akantu-oracle:dev (g++ $(g++ -dumpfullversion), Debian $(cat /etc/debian_version), $(uname -m)):"
    echo "# the inputs of gen_fixture.cc as evaluated on this host (some differ from complex_div_cleanroom.txt'"'"'s),"
    echo "# with this runtime'"'"'s results."
    echo "# Format: cdivx <tag> | a b c d | re im   (IEEE-754 bit patterns; tags: gen_fixture.cc)"
    cat /tmp/fixture.txt
  } > /out/complex_div_cleanroom_x86_64.txt
'
cat "$out/toolchain.txt" "$out/e28.txt" "$out/gen_fixture_stats.txt"
head -4 "$out/e1.txt"
grep -h "^E4" "$out/e4_model_v5.txt" "$out/e4_model_v6.txt"
