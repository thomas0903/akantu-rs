#!/usr/bin/env bash
# SPDX-License-Identifier: LGPL-3.0-or-later
# Build and run the product probe (gemm_probe.cc) against the strict
# oracle install inside the oracle image and write the fixture
# crates/akantu-linalg/tests/fixtures/dense/dense_gemm_strict.txt.
# Run from anywhere:
#
#   oracle/probes/dense/run_gemm.sh
#
# Read-only mount of the oracle build volume; nothing in the volume or the
# reference is modified. Strict configuration only (the bit-parity target,
# docs/NUMERICAL_VALIDATION.md).
set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")/../../scripts" && pwd)/oracle-env.sh"  # ORACLE_ENV_ARGS (D-050)
repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)
out="$repo/crates/akantu-linalg/tests/fixtures/dense"
mkdir -p "$out"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cp "$repo/oracle/probes/dense/gemm_probe.cc" "$work/"

docker run --rm ${ORACLE_ENV_ARGS[@]+"${ORACLE_ENV_ARGS[@]}"} --memory=4g --network none \
  -v akantu-oracle-build:/build:ro \
  -v "$work:/work" -w /work akantu-oracle:dev bash -euc '
    inst=/build/install-strict
    # D-050: the install'"'"'s Eigen cache-size pin (x86_64 only; empty on aarch64).
    pin=$(grep -o -e "-DEIGEN_NO_CPUID" -e "-DEIGEN_DEFAULT_L[123]_CACHE_SIZE=[0-9]*" \
            $inst/share/akantu-oracle/build-info.txt | sort -u | tr "\n" " " || true)
    g++ -std=c++20 -O2 -DNDEBUG -I/usr/include/eigen3 -DOMPI_SKIP_MPICXX \
      -ffp-contract=off -DEIGEN_DONT_VECTORIZE $pin \
      -I$inst/include/akantu -I$inst/include/akantu_iterators -I$inst/include \
      gemm_probe.cc -o gemm_probe -L$inst/lib -Wl,-rpath,$inst/lib -lakantu
    ./gemm_probe > strict.txt
    {
      echo "# image: $(cat /etc/debian_version 2>/dev/null) $(uname -m), g++ $(g++ -dumpfullversion)"
      echo "# eigen: $(grep -E "define EIGEN_(WORLD|MAJOR|MINOR)_VERSION" /usr/include/eigen3/Eigen/src/Core/util/Macros.h | awk "{print \$3}" | paste -sd.)"
    } > env.txt
  '
{
  echo "# Product fixture (D-036). Generated by oracle/probes/dense/run_gemm.sh"
  echo "# from the REAL upstream code (Akantu aka_types.hh / aka_voigthelper.hh at"
  echo "# 35a851780d0b9471d258ed53a003ae98aaa95ea0, Eigen 3.4.0) built with the strict"
  echo "# oracle flags: -std=c++20 -O2 -DNDEBUG -ffp-contract=off -DEIGEN_DONT_VECTORIZE"
  echo "# (install-strict). Format: oracle/probes/dense/README.md (product probe)."
  cat "$work/env.txt"
  cat "$work/strict.txt"
} > "$out/dense_gemm_strict.txt"
wc -lc "$out/dense_gemm_strict.txt"
grep -v '^#' "$out/dense_gemm_strict.txt" | awk '{print $1, $2}' | sort | uniq -c
