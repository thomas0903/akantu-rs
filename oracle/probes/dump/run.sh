#!/usr/bin/env bash
# SPDX-License-Identifier: LGPL-3.0-or-later
# Build the dumper probe against the installed oracle (akantu-oracle:dev,
# volume akantu-oracle-build mounted read-only) and regenerate
# fixtures/dump/<case>/ from the files the C++ dumpers write.
#
# Run on the host from the repository root:
#   oracle/probes/dump/run.sh
#
# Every case runs twice in fresh output directories; files that differ
# between the two runs are listed in fixtures/dump/<case>/NONDETERMINISTIC
# (upstream reads uninitialised memory in some derived fields). The exit
# status and stdout/stderr of each run go to fixtures/dump/<case>/status.txt.
# fixtures/dump/SHA256SUMS indexes every file (cd fixtures/dump && shasum -a
# 256 -c SHA256SUMS).
set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")/../../scripts" && pwd)/oracle-env.sh"  # ORACLE_ENV_ARGS (D-050)
repo="$(cd "$(dirname "$0")/../../.." && pwd)"
docker run --rm ${ORACLE_ENV_ARGS[@]+"${ORACLE_ENV_ARGS[@]}"} --memory 4g \
  -v akantu-oracle-build:/build:ro \
  -v "${AKANTU_SRC_HOST:?set AKANTU_SRC_HOST to the upstream Akantu checkout (commit 35a851780d0b)}":/akantu-src:ro \
  -v "$repo":/work \
  -w /work \
  akantu-oracle:dev bash -c '
set -euo pipefail
test -f /build/install-strict/READY
cmake -S oracle/probes/dump -B /tmp/probe -G Ninja \
      -DAKANTU_ORACLE_PREFIX=/build/install-strict >/dev/null
cmake --build /tmp/probe -j1 >/dev/null
out=/work/fixtures/dump
rm -rf "$out"
mkdir -p "$out"
cases="m2 m2_raw_qp all_types coh3d16 dkt18 groups parallel text text_mpi_mesh text_mpi_filtered lammps iohelper smm2d smm2d_strain_pad smm3d"
for c in $cases; do
  dat=""
  case $c in
    smm2d*) dat=/work/oracle/probes/dump/material_2d.dat ;;
    smm3d) dat=/work/oracle/probes/dump/material_3d.dat ;;
  esac
  for run in 1 2; do
    w=/tmp/run$run/$c
    rm -rf "$w"; mkdir -p "$w"
    cp /akantu-src/third-party/iohelper/test/cube.msh "$w/"
    set +e
    launcher=""
    case $c in text_mpi*) launcher="mpirun -np 2" ;; esac
    (cd "$w" && $launcher /tmp/probe/dump_probe "$c" "$w/out" $dat > "$w/stdout.txt" 2> "$w/stderr.txt")
    echo $? > "$w/exit_code"
    set -e
  done
  dst="$out/$c"
  mkdir -p "$dst"
  if [ -d /tmp/run1/$c/out ]; then cp -r /tmp/run1/$c/out/. "$dst/"; fi
  {
    echo "case: $c"
    echo "exit_code: $(cat /tmp/run1/$c/exit_code) (second run: $(cat /tmp/run2/$c/exit_code))"
    echo "--- stdout"
    cat /tmp/run1/$c/stdout.txt
    echo "--- stderr (first 20 lines)"
    head -20 /tmp/run1/$c/stderr.txt
  } > "$dst/status.txt"
  (cd /tmp/run1/$c/out 2>/dev/null && find . -type f | sort) | while read -r f; do
    if ! cmp -s "/tmp/run1/$c/out/$f" "/tmp/run2/$c/out/$f"; then
      echo "${f#./}" >> "$dst/NONDETERMINISTIC"
    fi
  done
done
# Upstream test test/test_io/test_dumper (binary of the strict build tree,
# run in a scratch copy of its inputs): oracle of the Rust port
# crates/akantu-io/tests/test_dumper.rs.
td=/build/strict/test/test_io/test_dumper
for run in 1 2; do
  w=/tmp/td$run
  rm -rf "$w"; mkdir -p "$w/paraview"
  cp "$td/input_file.dat" "$td/test_dumper.msh" "$w/"
  (cd "$w" && "$td/test_dumper" > stdout.txt 2> stderr.txt; echo $? > exit_code)
done
mkdir -p "$out/test_dumper"
cp -r /tmp/td1/paraview "$out/test_dumper/"
echo "exit_code: $(cat /tmp/td1/exit_code) (second run: $(cat /tmp/td2/exit_code))" > "$out/test_dumper/status.txt"
(cd /tmp/td1/paraview && find . -type f | sort) | while read -r f; do
  cmp -s "/tmp/td1/paraview/$f" "/tmp/td2/paraview/$f" || echo "paraview/${f#./}" >> "$out/test_dumper/NONDETERMINISTIC"
done
{
  echo "Generated by oracle/probes/dump/run.sh (probe oracle/probes/dump/dump_probe.cc)"
  echo "oracle: /build/install-strict (strict), scripts $(cat /build/install-strict/READY)"
  echo "reference: 35a851780d0b9471d258ed53a003ae98aaa95ea0"
  echo "image: $(cat /etc/debian_version) $(uname -m)"
  echo "compiler: $(g++ --version | head -1)"
  echo "date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
} > "$out/PROVENANCE.txt"
(cd "$out" && find . -type f ! -name SHA256SUMS | sed "s|^\./||" | LC_ALL=C sort | xargs sha256sum > SHA256SUMS)
'
