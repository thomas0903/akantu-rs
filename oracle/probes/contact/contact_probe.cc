void detection_flat_on_flat(const fs::path & root, const fs::path & up, const fs::path & fz) {
  const std::string cid = "model/contact/detection_flat_on_flat";
  auto dat = contact_dat("contact", "contact", 0., 1050e7, 0., false, "penalty_linear",
                         kElasticMaterials);
  auto input = write_input("flat_on_flat.dat", dat);
  auto mesh_file = fz / "test/test_model/test_contact_mechanics_model/flat_on_flat.msh";
  Coupled c(mesh_file);
  auto & pos = c.contact().getContactDetector().getPositions();
  const Real dx = 0.013, dy = 1e-3;
  const auto & upper = c.mesh.getElementGroup("upper").getNodeGroup().getNodes();
  for (auto n : upper) {
    pos(n, 0) += dx;
    pos(n, 1) -= dy;
  }
  ap::FixtureWriter w(root, cid,
                      "flat_on_flat.msh, master = slave = contact (two-pass), upper body shifted "
                      "by (0.013, -1e-3): one search and one force assembly (penalty_linear, "
                      "mu = 0, rigid master)",
                      kProbe, kProbeVersion);
  add_nodal(w, "positions", pos, "detector positions used for the search");
  c.contact().search();
  record_search(w, c.contact());
  w.add_input_file("mesh", mesh_file, "test/test_model/test_contact_mechanics_model/flat_on_flat.geo");
  w.add_input_file("material", input);
  w.finish();
  (void)up;
}

void detection_strait(const fs::path & root, const fs::path & fz, const std::string & mesh_name,
                      Real angle_deg) {
  std::stringstream id;
  id << "model/contact/detection_" << mesh_name;
  if (angle_deg != 0.) {
    id << "_rot" << static_cast<int>(angle_deg);
  }
  const std::string cid = id.str();
  if (not wanted(cid.substr(std::string("model/contact/").size()))) {
    return;
  }
  auto dat = contact_dat("master", "slave", 0., 1., 0., false, "penalty_linear", kElasticMaterials);
  auto input = write_input("detection.dat", dat);
  auto mesh_file =
      fz / ("test/test_model/test_contact_mechanics_model/test_detector/_detection_" + mesh_name + ".msh");
  Coupled c(mesh_file);
  auto & pos = c.contact().getContactDetector().getPositions();
  const Real delta = 1e-3;
  for (auto n : c.mesh.getElementGroup("slave_body").getNodeGroup().getNodes()) {
    pos(n, 1) += delta;
  }
  const Real a = angle_deg * M_PI / 180.;
  const Real ca = std::cos(a), sa = std::sin(a);
  for (Int n = 0; n < pos.size(); ++n) {
    const Real x = pos(n, 0), y = pos(n, 1);
    pos(n, 0) = ca * x - sa * y;
    pos(n, 1) = sa * x + ca * y;
  }
  ap::FixtureWriter w(root, cid,
                      "test_detector/_detection_" + mesh_name +
                          ".msh: slave body shifted by +1e-3 in y into the master body, positions "
                          "rotated by the angle parameter (degrees); one search + force assembly",
                      kProbe, kProbeVersion);
  w.parameters()["angle_deg"] = angle_deg;
  add_nodal(w, "positions", pos, "detector positions used for the search");
  c.contact().search();
  record_search(w, c.contact());
  w.add_input_file("mesh", mesh_file,
                   "test/test_model/test_contact_mechanics_model/test_detector/data/");
  w.add_input_file("material", input);
  w.finish();
}

