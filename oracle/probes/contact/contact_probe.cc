template <typename T> std::vector<T> arrange(T start, T stop, T step = 1) {
  std::vector<T> values;
  for (T value = start; value <= stop; value += step) {
    values.push_back(value);
  }
  return values;
}

std::vector<Real> schedule(Real d_max, Int steps) {
  auto xi = arrange<Real>(0, 1, 1. / steps);
  std::vector<Real> d;
  std::transform(xi.begin(), xi.end(), std::back_inserter(d), [&](Real & p) -> Real {
    return 0. + (d_max)*pow(p, 3) * (10 - 15 * p + 6 * pow(p, 2));
  });
  return d;
}

void damp(SolidMechanicsModel & solid, ContactMechanicsModel & contact, Real ratio) {
  auto & velocity = solid.getVelocity();
  auto & gaps = contact.getGaps();
  for (auto && tuple : zip(gaps, make_view(velocity, 2))) {
    auto & gap = std::get<0>(tuple);
    auto & vel = std::get<1>(tuple);
    if (gap > 0) {
      vel *= ratio;
    }
  }
}

