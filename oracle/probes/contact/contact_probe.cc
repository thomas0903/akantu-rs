/// Record the state of a search (contact elements, nodal geometry,
/// detector distances) and of the subsequent force assembly.
void record_search(ap::FixtureWriter & w, ContactMechanicsModel & contact,
                   const std::string & p = "", bool with_total = true) {
  const auto & elements = contact.getContactElements();
  std::vector<I64> slaves, masters, master_types;
  for (const auto & e : elements) {
    slaves.push_back(e.slave);
    masters.push_back(e.master.element);
    master_types.push_back(static_cast<I64>(e.master.type));
  }
  add_ivec(w, p + "contact_elements/slave", slaves, "entry", "slave node of each contact element");
  add_ivec(w, p + "contact_elements/master", masters, "entry",
           "master facet index (type in master_type)");
  if (p.empty()) {
    w.parameters()["master_types"] =
        std::string(elements.empty() ? "" : std::to_string(elements(0).master.type));
  }
  add_nodal(w, p + "gaps", contact.getGaps(), "gaps after search (penetration > 0)");
  add_nodal(w, p + "normals", contact.getNormals(), "normals");
  add_nodal(w, p + "tangents", contact.getTangents(), "tangents (dim x (dim-1) column-major)");
  add_nodal(w, p + "projections", contact.getProjections(), "natural projections");
  add_nodal(w, p + "areas", contact.getNodalArea(), "nodal areas");
  auto & det = contact.getContactDetector();
  add_scalars(w, p + "detector/distances",
              {det.getMaximumDetectionDistance(), det.getMinimumDetectionDistance(),
               det.getMaximumBoundingBox()},
              "max_dd, min_dd, max_bb");
  contact.assembleInternalForces();
  if (with_total) {
    add_nodal(w, p + "contact_force", contact.getInternalForce(), "internal_force after search");
  }
  add_nodal(w, p + "normal_force", contact.getNormalForce(), "normal_force");
  add_nodal(w, p + "tangential_force", contact.getTangentialForce(), "tangential_force");
  std::vector<I64> states;
  for (auto s : contact.getContactState()) {
    states.push_back(static_cast<I64>(s));
  }
  add_ivec(w, p + "contact_state", states, "node", "contact state (0 no contact, 1 stick, 2 slip)");
}

