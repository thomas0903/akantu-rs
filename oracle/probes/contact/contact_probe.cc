/// Local normal force and moduli of a probe-owned penalty_linear
/// (epsilon_n = 1e3) for every contact element.
void record_local_normal(ap::FixtureWriter & w, ContactMechanicsModel & contact, Int dim) {
  ResolutionPenalty lin(contact, "probe:0:penalty_linear");
  lin.set("epsilon_n", Real(1e3));
  std::vector<double> f_all, k_all;
  for (const auto & e : contact.getContactElements()) {
    const auto nd = e.getNbNodes() * dim;
    Vector<Real> f(nd);
    lin.computeNormalForce(e, f);
    f_all.insert(f_all.end(), f.data(), f.data() + nd);
    Matrix<Real> k(nd, nd);
    k.zero();
    lin.computeNormalModuli(e, k);
    k_all.insert(k_all.end(), k.data(), k.data() + nd * nd);
  }
  add_scalars(w, "local/normal_force_linear", f_all, "concatenated local normal forces");
  add_scalars(w, "local/normal_moduli_linear", k_all,
              "concatenated column-major nd x nd normal moduli");
}

