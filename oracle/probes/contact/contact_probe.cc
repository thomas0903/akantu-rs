void penalty_quadratic_construction(const fs::path & root, const fs::path & fz) {
  const std::string cid = "model/contact/penalty_quadratic_construction";
  auto dat = contact_dat("contact", "contact", 0., 1e3, 0., false, "penalty_linear", kElasticMaterials);
  auto input = write_input("quadratic.dat", dat);
  auto mesh_file = fz / "test/test_model/test_contact_mechanics_model/flat_on_flat.msh";
  Coupled c(mesh_file);
  std::string message;
  try {
    ResolutionPenaltyQuadratic quad(c.contact(), "probe:penalty_quadratic");
    message = "no exception";
  } catch (debug::Exception & e) {
    message = e.what();
  } catch (std::exception & e) {
    message = e.what();
  }
  ap::FixtureWriter w(root, cid,
                      "constructing ResolutionPenaltyQuadratic (the penalty_quadratic factory "
                      "allocator does the same) raises: its constructor calls the parent's "
                      "initialize() again and re-registers epsilon_n / epsilon_t (UD-370)",
                      kProbe, kProbeVersion);
  w.expect_error("exception", "already registered");
  w.parameters()["message"] = message;
  w.add_input_file("mesh", mesh_file, "test/test_model/test_contact_mechanics_model/flat_on_flat.geo");
  w.add_input_file("material", input);
  w.finish();
}

