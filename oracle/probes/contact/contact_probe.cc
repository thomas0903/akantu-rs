/// Lower top bent into z = -0.15 (x^2 + y^2) (warped facets), upper body
/// shifted by (sx, sy, sz), both from the mesh nodes.
void curved_positions(Coupled & c, Real sx, Real sy, Real sz) {
  auto & pos = c.contact().getContactDetector().getPositions();
  const auto & nodes = c.mesh.getNodes();
  for (auto n : c.mesh.getElementGroup("lower").getNodeGroup().getNodes()) {
    const Real x = nodes(n, 0), y = nodes(n, 1), z = nodes(n, 2);
    pos(n, 0) = x;
    pos(n, 1) = y;
    pos(n, 2) = z + (z + 1.) * (-0.15 * (x * x + y * y));
  }
  for (auto n : c.mesh.getElementGroup("upper").getNodeGroup().getNodes()) {
    pos(n, 0) = nodes(n, 0) + sx;
    pos(n, 1) = nodes(n, 1) + sy;
    pos(n, 2) = nodes(n, 2) + sz;
  }
}

