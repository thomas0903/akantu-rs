/* local moduli and assembled stiffness                                       */
/* -------------------------------------------------------------------------- */
void record_aij(ap::FixtureWriter & w, const std::string & prefix, const SparseMatrixAIJ & A) {
  const auto nnz = A.getNbNonZero();
  std::vector<I64> rows(nnz), cols(nnz);
  std::vector<double> vals(nnz);
  for (Int k = 0; k < nnz; ++k) {
    rows[k] = A.getIRN()(k);
    cols[k] = A.getJCN()(k);
    vals[k] = A.getA()(k);
  }
  add_ivec(w, prefix + "/irn", rows, "entry", "1-based row (getIRN)");
  add_ivec(w, prefix + "/jcn", cols, "entry", "1-based column (getJCN)");
  add_scalars(w, prefix + "/a", vals, "values (getA), first-insertion order");
  w.parameters()[prefix + "/symmetric"] = (A.getMatrixType() == _symmetric);
  w.parameters()[prefix + "/size"] = static_cast<long long>(A.size());
}

void moduli_tilted(const fs::path & root, const fs::path & fz) {
  const std::string cid = "model/contact/moduli_tilted";
  auto dat = contact_dat("contact", "contact", 0., 1e3, 0., true, "penalty_linear", kElasticMaterials);
  auto input = write_input("moduli.dat", dat);
  auto mesh_file = fz / "test/test_model/test_contact_mechanics_model/flat_on_flat.msh";
  Coupled c(mesh_file);
  auto & contact = c.contact();
  auto & pos = contact.getContactDetector().getPositions();
  // lower body tilted (rotation about the origin), upper body pushed in
  const Real a = 0.05;
  const Real ca = std::cos(a), sa = std::sin(a);
  for (auto n : c.mesh.getElementGroup("lower").getNodeGroup().getNodes()) {
    const Real x = pos(n, 0), y = pos(n, 1);
    pos(n, 0) = ca * x - sa * y;
    pos(n, 1) = sa * x + ca * y;
  }
  for (auto n : c.mesh.getElementGroup("upper").getNodeGroup().getNodes()) {
    pos(n, 0) += 0.007;
    pos(n, 1) -= 0.02;
  }
  ap::FixtureWriter w(root, cid,
                      "flat_on_flat.msh, lower body rotated by 0.05 rad, upper body shifted by "
                      "(0.007, -0.02); per contact element: local normal force and normal moduli "
                      "of a probe-owned penalty_linear (epsilon_n = 1e3), then the K assembled by "
                      "the model (penalty_linear, deformable master)",
                      kProbe, kProbeVersion);
  add_nodal(w, "positions", pos, "detector positions used for the search");
  contact.search();
  record_search(w, contact);
  ResolutionPenalty lin(contact, "probe:0:penalty_linear");
  lin.set("epsilon_n", Real(1e3));
  // penalty_quadratic cannot be constructed upstream (UD-370, case
  // penalty_quadratic_construction): its constructor re-registers the
  // penalty parameters.
  std::vector<double> f_lin, k_lin;
  std::vector<I64> offsets{0}, offsets2{0};
  for (const auto & e : contact.getContactElements()) {
    const auto nd = e.getNbNodes() * 2;
    Vector<Real> f(nd);
    lin.computeNormalForce(e, f);
    f_lin.insert(f_lin.end(), f.data(), f.data() + nd);
    Matrix<Real> k(nd, nd);
    k.zero();
    lin.computeNormalModuli(e, k);
    k_lin.insert(k_lin.end(), k.data(), k.data() + nd * nd);
    offsets.push_back(offsets.back() + nd);
    offsets2.push_back(offsets2.back() + nd * nd);
  }
  add_scalars(w, "local/normal_force_linear", f_lin, "concatenated local normal forces");
  add_scalars(w, "local/normal_moduli_linear", k_lin, "concatenated column-major nd x nd moduli");
  add_ivec(w, "local/force_offsets", offsets, "entry", "offsets into the forces");
  add_ivec(w, "local/moduli_offsets", offsets2, "entry", "offsets into the moduli");
  contact.assembleStiffnessMatrix();
  record_aij(w, "K", aka::as_type<SparseMatrixAIJ>(c.coupler->getDOFManager().getMatrix("K")));
  w.add_input_file("mesh", mesh_file, "test/test_model/test_contact_mechanics_model/flat_on_flat.geo");
  w.add_input_file("material", input);
  w.finish();
}

