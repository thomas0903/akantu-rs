std::set<std::string> wanted_cases() {
  std::set<std::string> s;
  const char * e = std::getenv("CONTACT_PROBE_CASES");
  if (e == nullptr) {
    return s;
  }
  std::stringstream ss(e);
  std::string one;
  while (std::getline(ss, one, ',')) {
    if (not one.empty()) {
      s.insert(one);
    }
  }
  return s;
}

bool wanted(const std::string & id) {
  static const auto w = wanted_cases();
  return w.empty() or w.count(id) > 0;
}

std::vector<double> vec_of(const Array<Real> & a) {
  return std::vector<double>(a.data(), a.data() + a.size() * a.getNbComponent());
}

std::string digest(const Array<Real> & a) {
  ap::Sha256 h;
  h.update(a.data(), a.size() * a.getNbComponent() * sizeof(double));
  return h.hex();
}

void add_nodal(ap::FixtureWriter & w, const std::string & name, const Array<Real> & a,
               const std::string & desc) {
  w.add(name, {static_cast<std::size_t>(a.size()), static_cast<std::size_t>(a.getNbComponent())},
        {"node", "component"}, "nodal", vec_of(a))
      .description(desc);
}

void add_scalars(ap::FixtureWriter & w, const std::string & name, const std::vector<double> & v,
                 const std::string & desc) {
  w.add(name, {v.size()}, {"entry"}, "table", v).description(desc);
}

void add_ivec(ap::FixtureWriter & w, const std::string & name, const std::vector<I64> & v,
              const std::string & axis, const std::string & desc) {
  w.add(name, {v.size()}, {axis}, "table", v).description(desc);
}

/// Write `text` to a scratch file, parse it as the static input file and
/// attach it as the input "material".
fs::path write_input(const std::string & file, const std::string & text) {
  auto tmp = fs::temp_directory_path() / ("contact_probe_" + file);
  std::ofstream f(tmp, std::ios::binary | std::ios::trunc);
  f << text;
  f.close();
  getStaticParser().parse(tmp.string());
  return tmp;
}

std::string contact_dat(const std::string & master, const std::string & slave, Real mu,
                        Real eps_n, Real eps_t, bool deformable, const std::string & law,
                        const std::string & materials) {
  std::stringstream s;
  s << std::setprecision(17);
  s << materials;
  s << "contact_detector [\n  type = explicit\n  master = " << master << "\n  slave = " << slave
    << "\n  projection_tolerance = 1e-10\n  max_iterations = 100\n  extension_tolerance = 1e-5\n]\n\n";
  s << "contact_resolution " << law << " [\n  name = contact\n  mu = " << mu
    << "\n  epsilon_n = " << eps_n << "\n  epsilon_t = " << eps_t
    << "\n  is_master_deformable = " << (deformable ? "true" : "false") << "\n]\n";
  return s.str();
}

