// port): runs the upstream contact mechanics model
// (src/model/contact_mechanics: ContactDetector, PhysicalSurfaceSelector,
// ResolutionPenalty/ResolutionPenaltyQuadratic) through the upstream
// CouplerSolidContact and records detection results, local penalty forces
// and moduli, the assembled contact stiffness and the explicit-dynamics
// trajectory of test_explicit_dynamic.cc for the Rust differential tests
// (crates/akantu-contact/tests/contact_fixtures.rs).
//
// Cases (fixture area model/contact/, fixture format v1):
//   detection_flat_on_flat        flat_on_flat.msh, master = slave = contact
//                                 (two-pass), upper body shifted (dx, -dy)
//   detection_<mesh>[_rotN]       test_detector meshes (triangle_3,
//                                 quadrangle_4, triangle_3_quadrangle_4):
//                                 slave body shifted into the master body,
//                                 positions rotated by N degrees (UD-363)
//   moduli_tilted                 flat_on_flat with a tilted master line:
//                                 local normal force / moduli of a probe-owned
//                                 penalty_linear resolution per contact
//                                 element (UD-368) and the K assembled by the
//                                 model's deformable-master resolution (UD-002)
//   penalty_quadratic_construction  error path: ResolutionPenaltyQuadratic
//                                 cannot be constructed upstream (UD-370)
//   explicit_dynamic              test_explicit_dynamic.cc, 2000 steps:
//                                 displacement schedule, per-step digests,
//                                 checkpoints, final stresses
//   explicit_friction             test_explicit_friction.cc, 10000 steps
//                                 (only meaningful on a UD-001 zero-init
//                                 patched build: friction workspaces are
//                                 uninitialised upstream; the case records
//                                 the patch list from the build environment)
//
// Review adversarial cases (v3; meshes generated by
// run-in-container.sh from oracle/probes/contact/meshes/*.geo and committed
// as fixture inputs):
//   adversarial_rot<N>            _detection_quadrangle_4.msh, slave body
//                                 pushed by 1e-3, positions rotated by N =
//                                 44, 45, 89, 90 degrees (UD-363: slow / no
//                                 convergence, singular Newton matrix);
//                                 search, forces, local normal moduli
//   adversarial_ridge<N>          ridge2d.msh, lower top bent into a ridge
//                                 y = -tan(N deg)|x| (N = 40, 44, 50): two
//                                 candidate facets with mirror-image
//                                 projections above the apex (tie: the last
//                                 accepted facet wins)
//   adversarial_curved3d          curved3d.msh (hexahedron_8, warped
//                                 quadrangle_4 master facets on
//                                 z = -0.15 (x^2 + y^2)): search, forces,
//                                 local normal moduli, assembled K
//   adversarial_curved3d_tri      the same on curved3d_tri.msh
//                                 (tetrahedron_4, triangle_3 facets)
//   adversarial_curved3d_friction curved3d.msh, mu = 0.3: 24 prescribed
//                                 sliding steps across master facet
//                                 boundaries (search + forces per step),
//                                 slip moduli at the end (UD-001 variant
//                                 only, like explicit_friction)
//   adversarial_tri_{edges,valley,fallback}
//                                 (UD-001 variant only) the review's
//                                 triangle cases of UD-372 on a probe-written
//                                 tetrahedral mesh: search and forces
//   adversarial_quadratic3d       curved3d_o2.msh (hexahedron_20,
//                                 quadrangle_8): the projection Newton
//                                 throws (computeD2NDS2 not implemented);
//                                 error-path case
//
// Every case is generated with Eigen's cache sizes pinned to its defaults
// (D-050): Eigen::setCpuCacheSizes(16384, 524288, 524288) at the start of
// main (recorded as parameters.eigen_cache_sizes in the v3 cases).
// Variant-only cases (explicit_friction, adversarial_curved3d_friction)
// refuse to run unless CONTACT_PROBE_VARIANT_PATCH, _SHA256 and _DEFECT
// name the oracle variant, which is recorded as parameters.oracle_variant.
//
// Usage: contact_probe <fixtures_root> <upstream_src_root> <frozen_meshes_root>
//                      [<generated_meshes_dir>]
// Environment: CONTACT_PROBE_CASES=<id>[,<id>...] restricts the run.

