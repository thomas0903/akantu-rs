/// The coupler of the upstream tests (explicit lumped mass): solid with a
/// physical-name material selector, contact with a physical surface
/// selector.
struct Coupled {
  Mesh mesh;
  std::unique_ptr<CouplerSolidContact> coupler;
  std::shared_ptr<PhysicalSurfaceSelector> selector;

  Coupled(const fs::path & mesh_file, AnalysisMethod method = _explicit_lumped_mass,
          Int dim = 2)
      : mesh(dim) {
    mesh.read(mesh_file.string());
    coupler = std::make_unique<CouplerSolidContact>(mesh);
    auto & solid = coupler->getSolidMechanicsModel();
    auto ms = std::make_shared<MeshDataMaterialSelector<std::string>>("physical_names", solid);
    solid.setMaterialSelector(ms);
    coupler->initFull(_analysis_method = method);
    selector = std::make_shared<PhysicalSurfaceSelector>(mesh);
    coupler->getContactMechanicsModel().getContactDetector().setSurfaceSelector(selector);
  }
  ContactMechanicsModel & contact() { return coupler->getContactMechanicsModel(); }
  SolidMechanicsModel & solid() { return coupler->getSolidMechanicsModel(); }
};

