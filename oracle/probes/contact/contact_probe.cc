void explicit_case(const fs::path & root, const fs::path & up, const fs::path & fz, bool friction) {
  const std::string name = friction ? "explicit_friction" : "explicit_dynamic";
  const std::string cid = "model/contact/" + name;
  const std::string tdir = "test/test_model/test_contact_mechanics_model/";
  const std::string mat = friction ? "material-friction.dat" : "material.dat";
  getStaticParser().parse((up / (tdir + mat)).string());
  auto mesh_file = fz / (tdir + (friction ? "sliding-block-2D.msh" : "flat_on_flat.msh"));
  Coupled c(mesh_file);
  auto & solid = c.solid();
  auto & contact = c.contact();
  if (friction) {
    solid.applyBC(BC::Dirichlet::FixedValue(0.0, _x), "lower");
    solid.applyBC(BC::Dirichlet::FixedValue(0.0, _y), "lower");
  } else {
    solid.applyBC(BC::Dirichlet::FixedValue(0.0, _x), "upper");
    solid.applyBC(BC::Dirichlet::FixedValue(0.0, _x), "lower");
  }
  Real time_step = solid.getStableTimeStep();
  time_step *= 0.05;
  c.coupler->setTimeStep(time_step);
  const Int normal_steps = friction ? 2500 : 2000;
  const Int shear_steps = friction ? 7500 : 0;
  auto normal = schedule(friction ? 2e-2 : 1e-2, normal_steps);
  auto shear = friction ? schedule(1e-1, shear_steps) : std::vector<Real>{};
  ap::FixtureWriter w(root, cid,
                      (friction ? std::string("test_explicit_friction.cc (sliding-block-2D.msh, "
                                              "material-friction.dat, 2500 + 7500 steps)")
                                : std::string("test_explicit_dynamic.cc (flat_on_flat.msh, "
                                              "material.dat, 2000 steps)")) +
                          ": prescribed-displacement schedule, per-step SHA-256 digests of the "
                          "solid displacement and the contact force, checkpoints",
                      kProbe, kProbeVersion);
  if (friction) {
    label_variant(w);
  }
  add_scalars(w, "schedule/normal", normal, "prescribed normal displacements per step");
  if (friction) {
    add_scalars(w, "schedule/shear", shear, "prescribed shear displacements per step");
  }
  add_scalars(w, "time_step", {time_step}, "0.05 x stable time step");
  const std::set<Int> checkpoints =
      friction ? std::set<Int>{0, 1, 10, 100, 1000, 2499, 2500, 2501, 5000, 9999}
               : std::set<Int>{0, 1, 2, 10, 100, 500, 1000, 1999};
  std::stringstream dig;
  std::vector<I64> nb_contacts;
  const Int total = normal_steps + shear_steps;
  for (Int s = 0; s < total; ++s) {
    if (friction) {
      if (s < normal_steps) {
        solid.applyBC(BC::Dirichlet::FixedValue(-normal[s], _y), "loading");
      } else {
        solid.applyBC(BC::Dirichlet::FixedValue(shear[s - normal_steps], _x), "loading");
      }
    } else {
      solid.applyBC(BC::Dirichlet::FixedValue(-normal[s], _y), "loading");
      solid.applyBC(BC::Dirichlet::FixedValue(normal[s], _y), "fixed");
    }
    c.coupler->solveStep();
    damp(solid, contact, 0.99);
    nb_contacts.push_back(contact.getContactElements().size());
    // every step for explicit_dynamic; every 25th (and the last) step for
    // the 10 000-step friction case (1 MiB per-case limit)
    const Int stride = friction ? 25 : 1;
    if (s % stride == 0 or s == total - 1) {
      dig << s << " " << digest(solid.getDisplacement()) << " "
          << digest(contact.getInternalForce()) << "\n";
    }
    if (checkpoints.count(s) > 0 and s < total) {
      record_state(w, "step_" + std::to_string(s), c);
    }
  }
  add_ivec(w, "nb_contact_elements", nb_contacts, "step", "contact elements after each step");
  {
    auto tmp = fs::temp_directory_path() / ("contact_probe_" + name + "_digests.txt");
    std::ofstream f(tmp, std::ios::binary | std::ios::trunc);
    f << dig.str();
    f.close();
    w.add_input_file("digests", tmp);
    fs::remove(tmp);
  }
  record_state(w, "final", c);
  const auto & stress = solid.getMaterial(friction ? "upper" : "upper").getStress(_quadrangle_4);
  add_scalars(w, "final/stress_upper", vec_of(stress), "stress of material upper (quadrangle_4)");
  w.add_input_file("mesh", mesh_file, tdir + (friction ? "sliding-block-2D.geo" : "flat_on_flat.geo"));
  w.add_input_file("material", up / (tdir + mat), tdir + mat);
  w.finish();
}


