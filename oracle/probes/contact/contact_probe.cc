/// Label of a case generated on an oracle variant (D-003 A, ADR proposal
/// "oracle variants"): the variant-only cases refuse to run without it, and
/// the build environment must record the patched resolution_penalty.cc.
void label_variant(ap::FixtureWriter & w) {
  const char * patch = std::getenv("CONTACT_PROBE_VARIANT_PATCH");
  const char * sha = std::getenv("CONTACT_PROBE_VARIANT_SHA256");
  const char * defect = std::getenv("CONTACT_PROBE_VARIANT_DEFECT");
  const char * patched = std::getenv("AKANTU_PROBE_PATCHES");
  if (patch == nullptr or sha == nullptr or defect == nullptr) {
    throw std::runtime_error("variant-only case without CONTACT_PROBE_VARIANT_{PATCH,SHA256,DEFECT}");
  }
  if (patched == nullptr or
      std::string(patched).find("resolution_penalty.cc") == std::string::npos) {
    throw std::runtime_error("variant-only case on a build without the patched "
                             "resolution_penalty.cc (AKANTU_PROBE_PATCHES)");
  }
  ap::Json v = ap::Json::object();
  v["patch"] = std::string(patch);
  v["sha256"] = std::string(sha);
  v["defect"] = std::string(defect);
  w.parameters()["oracle_variant"] = v;
}

void record_eigen_pin(ap::FixtureWriter & w) {
  ap::Json c = ap::Json::array();
  c.push(static_cast<long long>(kEigenL1));
  c.push(static_cast<long long>(kEigenL2));
  c.push(static_cast<long long>(kEigenL3));
  w.parameters()["eigen_cache_sizes"] = c;
}

