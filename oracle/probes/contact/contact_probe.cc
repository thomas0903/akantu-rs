void adversarial_tri(const fs::path & root, const std::string & which) {
  const std::string name = "tri_" + which;
  auto input = write_input("adversarial_tri.dat", kTriDat);
  auto mesh_file = fs::temp_directory_path() / "contact_probe_v81_tri.msh";
  write_tri_mesh(mesh_file);
  Coupled c(mesh_file, _explicit_lumped_mass, 3);
  auto & contact = c.contact();
  auto & pos = contact.getContactDetector().getPositions();
  std::string what;
  if (which == "edges") {
    auto bottom = bottom_nodes_sorted(c.mesh);
    if (bottom.size() != kTargets.size()) {
      throw std::runtime_error("adversarial_tri_edges: unexpected slave node count");
    }
    for (auto n : c.mesh.getElementGroup("upper").getNodeGroup().getNodes()) {
      pos(n, 2) -= 0.01;
    }
    for (std::size_t k = 0; k < bottom.size(); ++k) {
      pos(bottom[k], 0) = kTargets[k][0];
      pos(bottom[k], 1) = kTargets[k][1];
    }
    what = "flat master; the 16 slave nodes moved (x, y) onto triangle interiors, shared "
           "diagonals, grid lines and a vertex, upper body pushed 0.01 into the master";
  } else if (which == "valley") {
    for (auto n : c.mesh.getElementGroup("lower").getNodeGroup().getNodes()) {
      pos(n, 2) += (pos(n, 2) + 1.) * 0.15 * std::abs(pos(n, 0));
    }
    for (auto n : c.mesh.getElementGroup("upper").getNodeGroup().getNodes()) {
      pos(n, 0) += 0.013;
      pos(n, 1) += 0.007;
      pos(n, 2) -= 0.04;
    }
    what = "master bent into the valley z += (z + 1) 0.15 |x|, upper body shifted by (0.013, "
           "0.007, -0.04): slaves near the valley line closer to the extended far slope";
  } else {
    for (auto n : c.mesh.getElementGroup("upper").getNodeGroup().getNodes()) {
      pos(n, 0) += 0.43;
      pos(n, 1) += 0.007;
      pos(n, 2) -= 0.01;
    }
    what = "flat master, upper body shifted by (0.43, 0.007, -0.01): the slave column at x = "
           "1.03 projects outside every triangle (inside upstream's box)";
  }
  ap::FixtureWriter w(root, kAdvPrefix + name,
                      "review V81 adversarial (UD-372 triangle projection validity), UD-001 "
                      "zero-init oracle variant: two tetrahedral bodies whose master triangles "
                      "have their right angle at their first node (upstream's UD-363 metric is "
                      "exact on a flat master, its Newton converges); " + what +
                          "; mu = 0: search and forces",
                      kProbe, kProbeVersion);
  label_variant(w);
  record_eigen_pin(w);
  add_nodal(w, "positions", pos, "detector positions used for the search");
  contact.search();
  record_search(w, contact);
  w.add_input_file("mesh", mesh_file,
                   "written by the probe (write_tri_mesh: review V81 v81_probe.cc write_mesh)");
  w.add_input_file("material", input);
  w.finish();
  fs::remove(mesh_file);
}

int main(int argc, char * argv[]) {
  if (argc < 4) {
    std::cerr << "usage: contact_probe <fixtures_root> <upstream_src_root> <frozen_meshes_root> [<generated_meshes_dir>]\n";
    return 2;
  }
  // D-050: host-independent blocking of Eigen's dense kernels (Eigen's own
  // defaults, the aarch64 values); recorded in the v3 cases' parameters.
  Eigen::setCpuCacheSizes(kEigenL1, kEigenL2, kEigenL3);
  const fs::path root = argv[1], up = argv[2], fz = argv[3];
  const fs::path gm = argc > 4 ? fs::path(argv[4]) : fs::path();
  int aka_argc = 1;
  char * aka_argv[] = {argv[0], nullptr};
  char ** aka_argv_p = aka_argv;
  initialize(aka_argc, aka_argv_p);
  RandomGenerator<Idx>::seed(1);
  try {
    if (wanted("detection_flat_on_flat")) {
      detection_flat_on_flat(root, up, fz);
    }
    for (const std::string m : {"triangle_3", "quadrangle_4", "triangle_3_quadrangle_4"}) {
      detection_strait(root, fz, m, 0.);
    }
    detection_strait(root, fz, "quadrangle_4", 30.);
    detection_strait(root, fz, "quadrangle_4", 60.);
    if (wanted("moduli_tilted")) {
      moduli_tilted(root, fz);
    }
    if (wanted("penalty_quadratic_construction")) {
      penalty_quadratic_construction(root, fz);
    }
    if (wanted("explicit_dynamic")) {
      explicit_case(root, up, fz, false);
    }
    // explicit_friction is generated only when explicitly requested (it
    // needs the UD-001 zero-init patched build, see oracle/patches/).
    if (std::getenv("CONTACT_PROBE_CASES") != nullptr and wanted("explicit_friction")) {
      explicit_case(root, up, fz, true);
    }
    for (int a : {44, 45, 89, 90}) {
      adversarial_rot(root, fz, a);
    }
    if (not gm.empty()) {
      for (int a : {40, 44, 50}) {
        adversarial_ridge(root, gm, a);
      }
      adversarial_curved(root, gm, false);
      adversarial_curved(root, gm, true);
      adversarial_quadratic(root, gm);
      // variant only (UD-001 zero-init), like explicit_friction
      if (std::getenv("CONTACT_PROBE_CASES") != nullptr and
          wanted("adversarial_curved3d_friction")) {
        adversarial_curved_friction(root, gm);
      }
    }
    // variant only (UD-001 zero-init)
    for (const std::string which : {"edges", "valley", "fallback"}) {
      if (std::getenv("CONTACT_PROBE_CASES") != nullptr and wanted("adversarial_tri_" + which)) {
        adversarial_tri(root, which);
      }
    }
  } catch (std::exception & e) {
    std::cerr << "contact_probe: " << e.what() << std::endl;
    return 1;
  }
  finalize();
  return 0;
}
