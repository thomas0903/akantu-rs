#!/usr/bin/env python3
# SPDX-License-Identifier: LGPL-3.0-or-later
# Part of akantu-rs. Generates crates/akantu-core/src/glibc_libm/sincos_table.rs,
# the `__sincostab` table of the glibc `sin`/`cos` port in
# crates/akantu-core/src/glibc_libm/sincos.rs.
#
# The table is parsed from the BIG_ENDI block of glibc 2.41
# sysdeps/ieee754/dbl-64/sincostab.c (pairs `hi, lo` of 32-bit words) and
# located byte-for-byte in the oracle's /usr/lib/aarch64-linux-gnu/libm.so.6
# (Debian 2.41-12+deb13u4, sha256 a8afb2d1...), so the Rust table is exactly
# the data the oracle executes. The upstream notice of sincostab.c is
# reproduced in the generated header.
#
# Usage:
#   gen_sincos_table.py --sincostab <sincostab.c> --libm <libm.so.6> > sincos_table.rs
import argparse
import hashlib
import re
import struct
import sys

LIBM_SHA256 = "a8afb2d1f4a0c5e14c0fc82f794ec839eafe29738907aa92895410f57630bbe2"


def upstream_notice(text):
    start = text.index("/*")
    end = text.index("*/", start)
    out = []
    for line in text[start + 2:end].split("\n"):
        line = line.strip()
        if line == "*":
            line = ""
        elif line.startswith("* "):
            line = line[2:]
        out.append(line.rstrip())
    while out and not out[0]:
        out.pop(0)
    while out and not out[-1]:
        out.pop()
    body = "\n".join(out)
    if "version 2.1 of the License, or" not in body or "Copyright" not in body:
        sys.exit("sincostab.c: unexpected licence notice")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sincostab", required=True)
    ap.add_argument("--libm", required=True)
    a = ap.parse_args()
    text = open(a.sincostab).read()
    libm = open(a.libm, "rb").read()
    if hashlib.sha256(libm).hexdigest() != LIBM_SHA256:
        sys.exit("libm.so.6 is not the oracle's (sha256 mismatch)")
    block = text[text.index("#ifdef BIG_ENDI"):text.index("#else")]
    words = [int(w, 16) for w in re.findall(r"0x([0-9A-Fa-f]{8})", block)]
    if len(words) != 880:
        sys.exit(f"expected 880 words, got {len(words)}")
    vals = [(words[2 * i] << 32) | words[2 * i + 1] for i in range(440)]
    raw = b"".join(struct.pack("<Q", v) for v in vals)
    off = libm.find(raw)
    if off < 0 or libm.find(raw, off + 1) >= 0:
        sys.exit("table not found exactly once in libm.so.6")
    out = sys.stdout
    out.write("// SPDX-License-Identifier: LGPL-3.0-or-later\n//\n")
    out.write("// --- upstream notice of sincostab.c ---\n")
    for line in upstream_notice(text):
        out.write(("//   " + line).rstrip() + "\n")
    out.write(
        "//\n// Part of akantu-rs, a port of Akantu (EPFL/LSMS). Generated by\n"
        "// oracle/probes/random/gen_sincos_table.py from the BIG_ENDI block of glibc\n"
        "// 2.41 sysdeps/ieee754/dbl-64/sincostab.c; located byte-for-byte in the\n"
        f"// oracle's libm.so.6 (sha256 {LIBM_SHA256[:16]}..., file offset {off:#x}).\n"
        "// Distributed under LGPL-3.0-or-later via the \"or (at your option) any\n"
        "// later version\" grant (NOTICE.md, docs/DEPENDENCIES.md). Do not edit.\n\n"
        "//! glibc `__sincostab`: per entry `k` (`|x| ≈ k/128`) the values\n"
        "//! `sn, ssn, cs, ccs` (sin and cos of the table point, high and low parts).\n\n"
        "/// `__sincostab.x` as IEEE-754 bit patterns (440 doubles).\n"
        "pub(super) const SINCOSTAB: [u64; 440] = [\n"
    )
    for i in range(0, 440, 4):
        out.write("    " + " ".join(f"0x{v:016x}," for v in vals[i:i + 4]) + "\n")
    out.write("];\n")


if __name__ == "__main__":
    main()
