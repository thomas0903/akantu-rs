"""Generate every add_mesh() mesh with the image's Gmsh (D-009)."""

import hashlib
import json
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from add_mesh_calls import calls  # noqa: E402


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def msh_format(path: str) -> str:
    with open(path, "rb") as f:
        lines = f.read(256).split(b"\n")
    return lines[1].split()[0].decode() if len(lines) > 1 and lines[0].strip() == b"$MeshFormat" else "?"


def main() -> int:
    src, build, out = sys.argv[1:4]
    version = subprocess.run(["gmsh", "--version"], capture_output=True, text=True)
    gmsh_version = (version.stdout + version.stderr).strip().splitlines()[-1].strip()
    root = os.path.join(out, f"gmsh-{gmsh_version}")
    entries, failures = [], []
    for c in calls(src):
        geo = os.path.join(src, c["geo"])
        dest = os.path.join(root, c["output"])
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        cmd = ["gmsh", f"-{c['dim']}", "-order", str(c["order"]), "-o", dest, geo]
        with tempfile.TemporaryDirectory() as tmp:
            # Gmsh resolves Include/Merge relative to the .geo; run it in the
            # (read-only) source directory, HOME in a scratch directory.
            r = subprocess.run(cmd, cwd=os.path.dirname(geo), capture_output=True, text=True,
                               env={**os.environ, "HOME": tmp})
        if r.returncode != 0 or not os.path.isfile(dest):
            failures.append(f"{c['output']}: gmsh exit {r.returncode}: {r.stderr.strip()[-400:]}")
            continue
        copy = os.path.join(build, c["output"])
        committed = os.path.join(src, c["output"])
        if os.path.isfile(copy):
            if sha256(copy) == sha256(dest):
                build_copy = "identical"
            elif os.path.isfile(committed) and sha256(copy) == sha256(committed):
                # The build tree holds the committed file of the same name
                # (FILES_TO_COPY of another test); the Gmsh target was not built.
                build_copy = "build tree holds the committed file of the same name"
            else:
                build_copy = "different"
                failures.append(f"{c['output']}: differs from the oracle build tree copy")
        else:
            build_copy = "not built by the oracle"
        entries.append({
            **c,
            "command": f"gmsh -{c['dim']} -order {c['order']} -o <output> <geo>",
            "geo_sha256": sha256(geo),
            "path": os.path.relpath(dest, out),
            "sha256": sha256(dest),
            "bytes": os.path.getsize(dest),
            "msh_format": msh_format(dest),
            "oracle_build_copy": build_copy,
        })
        print(f"{build_copy:24s} {c['output']}", flush=True)
    meta = {
        "description": "Meshes generated by the reference at build time with add_mesh() "
                       "(cmake/Modules/FindGMSH.cmake), frozen per decision D-009. "
                       "Regenerate with oracle/probes/mesh_io/freeze-meshes.sh.",
        "reference_sha": os.environ.get("REF_SHA", "unknown"),
        "oracle_image": os.environ.get("ORACLE_IMAGE_ID", "unknown"),
        "gmsh_version": gmsh_version,
        "gmsh_package": subprocess.run(["dpkg-query", "-W", "-f=${Version}", "gmsh"],
                                       capture_output=True, text=True).stdout.strip(),
        "meshes": entries,
    }
    with open(os.path.join(out, "frozen_meshes.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=1)
        f.write("\n")
    if failures:
        print("\n".join(["FAILURES:"] + failures), file=sys.stderr)
        return 1
    print(f"{len(entries)} meshes frozen under {root}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
