copy_out() { # volume path-in-volume host-dir
  mkdir -p "$3"
  docker run --rm -u "$(id -u):$(id -g)" -v "$1:/vol:ro" -v "$3:/out" "${PERF_IMAGE}" \
    sh -c "cp -r /vol/$2/. /out/"
}
lines_in() { # perf-volume file -> line count (0 if absent)
  docker run --rm -v "${PERF_VOLUME}:/perf:ro" "${PERF_IMAGE}" sh -c "wc -l 2>/dev/null < $1 || echo 0"
}

# ---- partitions (C++ export) -------------------------------------------------
# A C++ run with export_partition = true writes partition.csv on rank 0 right
# after the Scotch partitioning, before mesh.distribute(); the rest of the
# run (distribution, init_full, the static solve: up to 0.35 h at the full
# size) is not needed for the export, so it is stopped once the file is
# complete (header + one line per element), unless --full-export.
export_partition() { # np -> ${out}/partition-np<np>.csv; returns 0 iff complete
  local np=$1 rd="/perf/runs/${campaign}/part/np$1/rep1" name="${prefix}-export-np$1-$$" n st pid
  log "partition np${np}: export run (C++, 1 step, export_partition = true)"
  (
    PERF_RUN_OPTS+=(--name "${name}")
    perf_docker bash /harness/scripts/in-container/run-one.sh "${rd}" "${cfg}" "${np}" cohesive "${cpp_mesh}" 1 \
      blocked_node=global export_partition=true "${extra[@]}"
  ) > "${out}/part-np${np}.log" 2>&1 &
  pid=$!
  while kill -0 "${pid}" 2>/dev/null; do
    sleep 3
    [ "${full_export}" = 1 ] && continue
    n=$(lines_in "${rd}/partition.csv")
    if [ "${n}" = $((n_elements + 1)) ]; then
      log "partition np${np}: partition.csv complete (${n_elements} elements): stopping the export run"
      docker stop -t 10 "${name}" > /dev/null 2>&1
      break
    fi
  done
  wait "${pid}"; st=$?
  n=$(lines_in "${rd}/partition.csv")
  if [ "${n}" != $((n_elements + 1)) ]; then
    log "partition np${np}: FAILED (export run status ${st}, partition.csv ${n} lines, expected $((n_elements + 1)))"
    return 1
  fi
  docker run --rm -v "${PERF_VOLUME}:/perf:ro" "${PERF_IMAGE}" cat "${rd}/partition.csv" > "${out}/partition-np${np}.csv.tmp" \
    && mv "${out}/partition-np${np}.csv.tmp" "${out}/partition-np${np}.csv" || return 1
  log "partition np${np} exported (sha256 $(sha256sum "${out}/partition-np${np}.csv" | cut -c1-16)…, run status ${st})"
}

for np in ${ranks}; do
  [ "${np}" -gt 1 ] || continue
  if [ -n "${partitions}" ] && [ "${mode}" = campaign ]; then
    cp "${partitions}/partition-np${np}.csv" "${out}/partition-np${np}.csv" \
      || { log "refused: no ${partitions}/partition-np${np}.csv"; exit 3; }
  else
    export_partition "${np}" || { log "campaign FAILED: no partition for np=${np}"; exit 1; }
  fi
  docker run --rm -i -u 0 -v "${tvol}:/target" "${PERF_IMAGE}" sh -c \
    "cat > /target/c1prep/${campaign}/partition-np${np}.csv && chmod a+r /target/c1prep/${campaign}/partition-np${np}.csv" \
    < "${out}/partition-np${np}.csv" || { log "campaign FAILED: partition np${np} not copied"; exit 1; }
done
if [ "${mode}" = export ]; then
  exit 0
fi

# ---- runs --------------------------------------------------------------------
classify() { # dest case np -> writes dest/status.txt, prints the outcome
  local d=$1 c=$2 np=$3
  python3 -I - "$d" "$c" "$np" "${out}/partition-np$3.csv" <<'PY'
import json, sys
from pathlib import Path
d, case, np, part = Path(sys.argv[1]), sys.argv[2], int(sys.argv[3]), Path(sys.argv[4])
MARKERS = ("MUMPS dynamic memory is insufficient", "The MUMPS workarray is too small",
           "Error in mumps during solve process", "Warning in mumps during solve process")
def text(name):
    p = d / name
    return p.read_text(errors="replace") if p.exists() else ""
def num(s):
    try:
        return int(s.strip())
    except (AttributeError, ValueError):
        return None
st = {"case": case, "np": np}
if case.startswith("cpp"):
    run = json.loads(text("run.json")) if (d / "run.json").exists() else {}
    st["exit"] = run.get("exit_status")
    st["oom_kills"] = run.get("container_oom_kills")
    st["memory_peak_bytes"] = run.get("container_memory_peak_bytes")
    st["memory_max"] = run.get("container_memory_max")
    st["aborted"] = run.get("aborted")
    st["ud216_markers"] = sum(text(n).count(m) for n in ("out.txt", "err.txt") for m in MARKERS)
    st["wall_s"] = run.get("wall_s")
    if np > 1:
        st["partition_matches"] = (d / "partition.csv").exists() and part.exists() \
            and (d / "partition.csv").read_bytes() == part.read_bytes()
else:
    st["exit"] = num(text("exit"))
    st["oom_kills"] = num(text("oom_kills"))
    st["memory_peak_bytes"] = num(text("memory_peak"))
    lim = dict(l.split(" ", 1) for l in text("limits.txt").splitlines() if " " in l)
    st["memory_max"] = lim.get("memory.max")
    st["cpu_max"] = lim.get("cpu.max")
    st["docker_exit"] = num(text("docker_exit"))
    try:
        st["wall_s"] = float(text("wall.txt"))
    except ValueError:
        st["wall_s"] = None
if st.get("oom_kills") or st.get("docker_exit") == 137:
    outcome = "oom"
elif case.startswith("cpp") and (st.get("aborted") or st.get("ud216_markers")):
    outcome = "ud216"   # upstream's MUMPS retry path: the static solution is wrong (UD-216)
elif st.get("exit") == 0 and (case.startswith("rust") or st.get("partition_matches", True)):
    outcome = "ok"
else:
    outcome = "failed"
st["outcome"] = outcome
(d / "status.txt").write_text("".join(f"{k}={json.dumps(v)}\n" for k, v in st.items()))
print(outcome)
PY
}

nfail=0 failed_runs=""
run_case() { # case np rep
  local c=$1 np=$2 rep=$3 dest="${out}/$1/np$2/rep$3" sp pids outcome dexit
  if [ -e "${dest}" ]; then dest="${dest}.again-$(date +%s)"; fi
  mkdir -p "$(dirname "${dest}")"
  pids=$(foreign_driver)
  if [ -n "${pids// /}" ]; then
    log "refused: cohesive_extrinsic processes already run on this host (pids${pids}); one run at a time"
    exit 3
  fi
  python3 -I "${here}/memsample.py" "${dest}.mem.jsonl" & sp=$!
  log "start ${c} np${np} rep${rep} (memory ${memory}$([ "${c#rust}" != "${c}" ] && echo ", cpus ${cpus}"))"
  case "${c}" in
    cpp|cppeig)
      local solver=""
      [ "${c}" = cppeig ] && solver=eigen
      local part=()
      [ "${np}" -gt 1 ] && part=(export_partition=true)
      (
        PERF_RUN_OPTS+=(--name "${prefix}-${c}-np${np}-$$")
        # shellcheck disable=SC2207 # plain tokens without spaces
        PERF_RUN_OPTS+=($(cpuset_for "${np}"))
        PERF_STATIC_SPARSE_SOLVER="${solver}" perf_docker bash /harness/scripts/in-container/run-one.sh \
          "/perf/runs/${campaign}/${c}/np${np}/rep${rep}" "${cfg}" "${np}" cohesive "${cpp_mesh}" "${steps}" \
          blocked_node=global energy_precision=17 output_energy=true "${part[@]}" "${extra[@]}"
      ) > "${dest}.launch.log" 2>&1
      kill "${sp}"; wait "${sp}" 2>/dev/null
      copy_out "${PERF_VOLUME}" "runs/${campaign}/${c}/np${np}/rep${rep}" "${dest}"
      ;;
    rust|rusteig)
      local solver=auto part=-
      [ "${c}" = rusteig ] && solver=eigen
      [ "${np}" -gt 1 ] && part="/target/c1prep/${campaign}/partition-np${np}.csv"
      local rd="/target/c1prep/${campaign}/${c}/np${np}/rep${rep}-$(date +%s)"
      # plain docker run (the repository subset has no scripts/mpi): the same
      # limits as the C++ container (--memory without swap, --shm-size 4g,
      # --init) plus the CPU quota
      # shellcheck disable=SC2046 # plain tokens without spaces
      docker run --rm --init --name "${prefix}-${c}-np${np}-$$" $(cpuset_for "${np}" "${rust_threads:-1}") \
        --memory "${memory}" --memory-swap "${memory}" --cpus "${cpus}" --shm-size 4g ${rust_env[@]+"${rust_env[@]}"} \
        -v "${tvol}:/target" -v "${repo}:/src:ro" -w /src "${rust_image}" \
        bash /src/crates/akantu-bench/scripts/c1prep_campaign.sh --rust-run \
        "${rd}" "${np}" "${steps}" "${rust_mesh}" "${part}" "${solver}" "${rust_bin}" "${extra[@]}" \
        ${rust_extra[@]+"${rust_extra[@]}"} \
        > "${dest}.launch.log" 2>&1
      dexit=$?
      kill "${sp}"; wait "${sp}" 2>/dev/null
      copy_out "${tvol}" "${rd#/target/}" "${dest}"
      echo "${dexit}" > "${dest}/docker_exit"
      ;;
    *) kill "${sp}"; echo "unknown case ${c}"; exit 2 ;;
  esac
  mv "${dest}.mem.jsonl" "${dest}/mem.jsonl"
  mv "${dest}.launch.log" "${dest}/launch.log"
  outcome=$(classify "${dest}" "${c}" "${np}")
  log "end ${c} np${np} rep${rep}: ${outcome:-failed} -> ${dest}"
  if [ "${outcome}" != ok ]; then
    nfail=$((nfail + 1))
    failed_runs="${failed_runs} ${c}/np${np}/rep${rep}=${outcome:-failed}"
  fi
}

