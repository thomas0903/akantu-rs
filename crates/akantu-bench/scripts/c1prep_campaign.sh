#!/usr/bin/env bash
# SPDX-License-Identifier: LGPL-3.0-or-later
# Part of akantu-rs, a Rust port of Akantu (EPFL/LSMS). No upstream
# counterpart: interleaved campaign of the cohesive scalability
# test, C++ harness (benchmarks/cohesive-perf, oracle image, run-one.sh) and
# Rust driver (crates/akantu-bench, features mpi,scotch,mumps), on a Linux
# host with Docker (an x86_64 Linux host or the full-size host). Runs from a full checkout or from the repository subset of
# c1_images.sh (it needs only benchmarks/cohesive-perf, this directory and
# the frozen h = 0.12 mesh). One run at a time (enforced, see below).
#
#   bash crates/akantu-bench/scripts/c1prep_campaign.sh [options] CAMPAIGN H STEPS "RANKS" REPS "CASES" [key=value ...]
#   bash crates/akantu-bench/scripts/c1prep_campaign.sh [options] --export-partition CAMPAIGN H NP
#     H      0.12 (the frozen fixture mesh), a number (a mesh generated by
#            benchmarks/cohesive-perf/scripts/gen-meshes.sh: /perf/meshes/cube-h<H>.msh)
#            or a name such as `joss` (/perf/meshes/cube-<name>.msh, copied into the
#            perf volume beforehand, e.g. by c1_session.sh)
#     CASES  cpp     C++ harness, CPP_CONFIG install, static solve MUMPS (upstream `_auto`)
#            cppeig  the same with sparse_solver_type = eigen (static solve)
#            rust    Rust driver, the input's `_auto` = MUMPS (feature mumps)
#            rusteig Rust driver, rust_sparse_solver = eigen (centralised on rank 0 if P > 1)
#     key=value  extra user-section parameters for both sides
#   --export-partition: only the C++ partition export for NP ranks (below),
#            written to OUT/CAMPAIGN/partition-np<NP>.csv; exit 0 iff complete.
#
# Options (the settings that change a result or a cost are arguments):
#   --memory M       container memory limit of BOTH codes, no swap (default 14g, an x86_64
#                    `large`; the full-size host: 480g on 512 GiB). A run above it is
#                    OOM-killed (outcome `oom`).
#   --cpus N         CPU quota of the Rust container (default 8; the full-size host: its
#                    core count, 64). The C++ container has no CPU quota (run-one.sh).
#   --partitions DIR use DIR/partition-np<N>.csv (from --export-partition) at every N > 1
#                    instead of exporting the partition at the start of the campaign
#   --rust-image I   Rust image (default akantu-rs-mumps:dev with the driver in the target
#                    volume; akantu-rs-bench:c1 on a new host, c1_images.sh)
#   --rust-bin PATH  driver path inside the Rust image (default
#                    /target/c1/release/cohesive_extrinsic in the target volume;
#                    /usr/local/bin/cohesive_extrinsic in akantu-rs-bench:c1)
#   --rust-volume V  Docker volume for the Rust side's meshes, partitions and run
#                    directories, mounted at /target (default akantu-rs-mpi-target)
#   --rust-extra "K=V ..."  user-section parameters of the Rust runs only (not the C++ ones),
#                    e.g. "rust_cohesive_compat=upstream rust_doubled_node_load=follows_elements"
#                    (the full-size rerun's settings, D-105 / D-108; c1_session.py passes them)
#   --rust-threads T threads per rank of the Rust runs (AKANTU_NUM_THREADS = T, default
#                    unset = 1); with T > 1 mpirun maps every rank on T consecutive cores
#                    (--map-by slot:PE=T --bind-to core), so give the run P x T cores
#                    (PIN_CPUS_FROM, the container's cpuset, takes P x T)
#   --rust-precision bitwise|fast  AKANTU_PRECISION of the Rust runs (default unset = bitwise)
#   --full-export    let the partition-export run finish (default: it is stopped as soon
#                    as partition.csv is complete, before the static solve; see below)
# env: CPP_CONFIG (strict), FNTE (joss: JOSS-patch emulation of the C++
#      fillNodesToElements rebuild; upstream = the oracle's behaviour), OUT
#      (~/c1prep-results), PERF_VOLUME / ORACLE_VOLUME (the harness's volumes,
#      benchmarks/cohesive-perf/scripts/common.sh), C1_CONTAINER_PREFIX
#      (c1prep: container names <prefix>-<case>-np<N>-<pid>, so that a session
#      can stop them), C1PREP_LOCK (/tmp/c1prep-campaign.lock), PIN_CPUS_FROM
#      (optional core number K: a run on N ranks gets the cores K..K+N-1 of
#      the host, docker --cpuset-cpus, both codes; recorded in provenance.txt).
#      The former environment variables MEMORY, CPUS, RUST_IMAGE, RUST_BIN are
#      still read as defaults of the options.
#
# Problem: benchmarks/cohesive-perf/inputs/material-cohesive.dat with
# max_steps = STEPS, blocked_node = global (the 1-rank problem at every rank
# count, UD-349), output_energy = true, energy_precision = 17. Both sides
# read the same mesh bytes (SHA-256 recorded) and, at P > 1, the same
# partition: a C++ run per rank count exports its Scotch partition
# (AKA_SEED = 1, SCOTCH_PTHREAD_NUMBER = 1); the harness writes partition.csv
# on rank 0 before it distributes the mesh, so the export run is stopped
# once the file holds one line per mesh element (unless --full-export); the
# C++ runs re-create it (export_partition = true; compared with the export
# after every run: `partition_matches` in status.txt) and the Rust runs
# replay it (rust_partitioner = file:). Thread counts: OMP, OpenBLAS, Scotch
# = 1 on both sides; OpenBLAS core pinned to Haswell by both images (D-050).
# Order: repetition k runs the rank counts in order and, per rank count, the
# cases rotated by k (timing noise).
#
# One run at a time: memsample.py samples every `cohesive_extrinsic` process
# on the host, so its peaks belong to the run only if
# nothing else runs. Enforced: the campaign holds an exclusive lock
# (C1PREP_LOCK) and refuses to start a run while any other
# `cohesive_extrinsic` process exists on the host.
#
# Outputs on the host: OUT/CAMPAIGN/<case>/np<N>/rep<k>/ (the run directory
# plus mem.jsonl, launch.log and status.txt: outcome ok | oom | ud216 |
# failed, exit, oom_kills, container memory peak and limit), provenance.txt,
# schedule.log, partition-np<N>.csv; then c1prep_analyze.py (summary.md,
# summary.json). Exit status: 0 iff every run's outcome is `ok` and the
# analysis succeeded; 1 otherwise ("campaign FAILED: ..." on stderr and in
# schedule.log); 2 usage; 3 refused (lock, foreign process, missing mesh).
set -uo pipefail
repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
here="${repo}/crates/akantu-bench/scripts"

# The Rust driver's input: the template with max_steps, mesh and output_energy
# replaced and, right after `user section [`, blocked_node = global,
# energy_precision = 17, the partition and solver lines and every key=value
# (with --rust-extra: the port's settings, e.g. rust_cohesive_compat /
# rust_doubled_node_load). awk, not sed, so that the offline test (BSD tools)
# and the container (GNU tools) write the same bytes (the
# output is byte-identical to the former sed's, checked on C1's input.dat).
rust_input() { # template steps mesh partition solver [key=value...] -> stdout
  local tpl=$1 steps=$2 mesh=$3 part=$4 solver=$5 extra kv
  shift 5
  extra="  blocked_node = global\n  energy_precision = 17"
  [ "${part}" = "-" ] || extra="${extra}\n  rust_partitioner = file:${part}"
  [ "${solver}" = "auto" ] || extra="${extra}\n  rust_sparse_solver = ${solver}"
  for kv in "$@"; do extra="${extra}\n  ${kv%%=*} = ${kv#*=}"; done
  awk -v steps="${steps}" -v mesh="${mesh}" -v extra="${extra}" '
    /^  max_steps = / { print "  max_steps = " steps; next }
    /^  mesh = / { print "  mesh = " mesh; next }
    /^  output_energy = / { print "  output_energy = true"; next }
    $0 == "user section [" { print; print extra; next }
    { print }' "${tpl}"
}
if [ "${1:-}" = "--rust-input" ]; then # offline: the input of a Rust run on stdout
  shift
  [ $# -ge 5 ] || { echo "usage: $0 --rust-input TEMPLATE STEPS MESH PARTITION|- SOLVER [key=value...]" >&2; exit 2; }
  rust_input "$@"
  exit $?
fi

if [ "${1:-}" = "--rust-run" ]; then # inside the Rust image: dir np steps mesh partition solver binary [key=value...]
  d=$2 np=$3 steps=$4 mesh=$5 part=$6 solver=$7 bin=$8; shift 8
  mkdir -p "${d}" && cd "${d}" || exit 1
  rust_input /src/benchmarks/cohesive-perf/inputs/material-cohesive.dat "${steps}" "${mesh}" "${part}" "${solver}" \
    "$@" > input.dat
  # the container's limits as the kernel sees them (cgroup v2)
  { echo "memory.max $(cat /sys/fs/cgroup/memory.max 2>/dev/null || echo unknown)"
    echo "cpu.max $(cat /sys/fs/cgroup/cpu.max 2>/dev/null || echo unknown)"
    echo "nproc $(nproc)"; } > limits.txt
  export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 SCOTCH_PTHREAD_NUMBER=1
  # the execution policy of the port (--rust-threads / --rust-precision): set
  # in the container's environment by the campaign, forwarded to every rank
  exec_opts=()
  if [ -n "${AKANTU_NUM_THREADS:-}" ]; then
    exec_opts+=(-x AKANTU_NUM_THREADS)
    [ "${AKANTU_NUM_THREADS}" -le 1 ] || exec_opts+=(--map-by "slot:PE=${AKANTU_NUM_THREADS}" --bind-to core)
  fi
  [ -z "${AKANTU_PRECISION:-}" ] || exec_opts+=(-x AKANTU_PRECISION)
  t0=$(date +%s.%N)
  mpirun -np "${np}" -x OMP_NUM_THREADS -x OPENBLAS_NUM_THREADS -x OPENBLAS_CORETYPE \
    -x SCOTCH_PTHREAD_NUMBER ${exec_opts[@]+"${exec_opts[@]}"} "${bin}" --aka_input_file input.dat > out.txt 2> err.txt
  echo $? > exit
  t1=$(date +%s.%N)
  python3 -c "print(f'{${t1}-${t0}:.3f}')" > wall.txt
  oom=unknown
  if [ -r /sys/fs/cgroup/memory.events ]; then
    while read -r k v; do if [ "${k}" = oom_kill ]; then oom="${v}"; fi; done < /sys/fs/cgroup/memory.events
  fi
  echo "${oom}" > oom_kills
  cat /sys/fs/cgroup/memory.peak > memory_peak 2>/dev/null || echo unknown > memory_peak
  sha256sum "${bin}" > binary.sha256
  exit 0
fi

usage() { sed -n '12,/^# Problem:/p' "$0" | sed '$d'; exit 2; }
memory="${MEMORY:-14g}" cpus="${CPUS:-8}" partitions="" full_export=0 rust_extra=()
rust_threads="" rust_precision=""
rust_image="${RUST_IMAGE:-akantu-rs-mumps:dev}"
rust_bin="${RUST_BIN:-/target/c1/release/cohesive_extrinsic}"
tvol="${RUST_VOLUME:-akantu-rs-mpi-target}"
mode=campaign
while [ $# -gt 0 ]; do
  case "$1" in
    --memory) memory=${2:?}; shift 2 ;;
    --cpus) cpus=${2:?}; shift 2 ;;
    --partitions) partitions=${2:?}; shift 2 ;;
    --rust-image) rust_image=${2:?}; shift 2 ;;
    --rust-bin) rust_bin=${2:?}; shift 2 ;;
    --rust-volume) tvol=${2:?}; shift 2 ;;
    --rust-extra) read -r -a rust_extra <<< "${2?}"; shift 2 ;;
    --rust-threads) rust_threads=${2:?}; shift 2 ;;
    --rust-precision) rust_precision=${2:?}; shift 2 ;;
    --full-export) full_export=1; shift ;;
    --export-partition) mode=export; shift ;;
    -h|--help) usage ;;
    --*) echo "unknown option $1" >&2; usage ;;
    *) break ;;
  esac
done
if [ "${mode}" = export ]; then
  [ $# -eq 3 ] || usage
  campaign=$1 h=$2 ranks=$3 steps=1 reps=0 cases=""
  shift 3
else
  [ $# -ge 6 ] || usage
  campaign=$1 h=$2 steps=$3 ranks=$4 reps=$5 cases=$6; shift 6
fi
extra=("$@")
cd "${repo}" || exit 1
export PERF_MEMORY="${memory}"
# shellcheck source=../../../benchmarks/cohesive-perf/scripts/common.sh
. benchmarks/cohesive-perf/scripts/common.sh
perf_check_campaign "${campaign}" || exit 2
perf_check_posint cpus "${cpus}" || exit 2
perf_check_posint_list ranks "${ranks}" || exit 2
[ "${mode}" = export ] || perf_check_posint steps "${steps}" || exit 2
[ "${mode}" = export ] || perf_check_posint reps "${reps}" || exit 2
[ "${mode}" = export ] || perf_check_enum_list cases "${cases}" cpp cppeig rust rusteig || exit 2
for kv in "${extra[@]}"; do perf_check_kv "${kv}" || exit 2; done
for kv in ${rust_extra[@]+"${rust_extra[@]}"}; do perf_check_kv "${kv}" || exit 2; done
[ -z "${rust_threads}" ] || perf_check_posint rust-threads "${rust_threads}" || exit 2
[ -z "${rust_precision}" ] || perf_check_enum rust-precision "${rust_precision}" bitwise fast || exit 2
rust_env=()
[ -z "${rust_threads}" ] || rust_env+=(-e "AKANTU_NUM_THREADS=${rust_threads}")
[ -z "${rust_precision}" ] || rust_env+=(-e "AKANTU_PRECISION=${rust_precision}")
cfg="${CPP_CONFIG:-strict}"
perf_check_config "${cfg}" || exit 2
export AKANTU_RS_FILL_NODES_TO_ELEMENTS="${FNTE:-joss}"
perf_check_fnte "${AKANTU_RS_FILL_NODES_TO_ELEMENTS}" || exit 2
prefix="${C1_CONTAINER_PREFIX:-c1prep}"
cpuset_for() { # np [threads] -> docker arguments pinning the run to PIN_CPUS_FROM.. (none without it)
  [ -n "${PIN_CPUS_FROM:-}" ] || return 0
  echo "--cpuset-cpus ${PIN_CPUS_FROM}-$((PIN_CPUS_FROM + $1 * ${2:-1} - 1))"
}
out="${OUT:-${HOME}/c1prep-results}/${campaign}"
mkdir -p "${out}"
