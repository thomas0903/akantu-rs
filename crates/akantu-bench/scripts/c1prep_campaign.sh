  esac
  {
    echo "campaign=${campaign} h=${h} steps=${steps} ranks=${ranks} reps=${reps} cases=${cases} extra=${extra[*]:-}"
    echo "date=$(date -u +%FT%TZ) revision=${rev} dirty=${dirty} partitions=${partitions:-exported}"
    echo "host_cpu=$(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2- | sed 's/^ //') nproc=$(nproc) kernel=$(uname -r)"
