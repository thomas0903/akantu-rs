# ---- one run at a time -------------------------------------------------
exec 9> "${C1PREP_LOCK:-/tmp/c1prep-campaign.lock}"
flock -n 9 || { echo "refused: another c1prep campaign holds ${C1PREP_LOCK:-/tmp/c1prep-campaign.lock}" \
  "(one run at a time: memsample.py samples host-wide)" >&2; exit 3; }
foreign_driver() { # prints the pids of cohesive_extrinsic processes on the host
  local p c pids=""
  for p in /proc/[0-9]*; do
    c=$(cat "${p}/comm" 2>/dev/null) || continue
    [ "${c}" = cohesive_extrin ] && pids="${pids} ${p#/proc/}"
  done
  echo "${pids}"
}

# ---- mesh: same bytes on both sides ---------------------------------------
if [ "${h}" = "0.12" ]; then
  perf_volume_write /perf/meshes/frozen-cube-h0.12.msh < fixtures/perf_cohesive/meshes/cube-h0.12.msh
  cpp_mesh=/perf/meshes/frozen-cube-h0.12.msh
elif [[ "${h}" =~ ^[a-z][a-z0-9]{0,15}$ ]]; then
