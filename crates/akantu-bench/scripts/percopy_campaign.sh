#!/usr/bin/env bash
# SPDX-License-Identifier: LGPL-3.0-or-later
# Part of akantu-rs, a Rust port of Akantu (EPFL/LSMS). No upstream
# counterpart: runs of the cohesive driver with the per-copy check
# of the loads (rust_load_check_*, crates/akantu-bench/src/load_check.rs) on
# the frozen h = 0.12 cube and generated meshes, on a Linux host with Docker
# an x86_64 Linux host with the oracle image and its build volume. Run it from a
# clone of the repository, not from the synced ~/akantu-rs (gen-meshes.sh
# writes mesh statistics into the checkout).
#
#   bash crates/akantu-bench/scripts/percopy_campaign.sh setup "H..."
#       the Rust release driver with MPI, Scotch and MUMPS (/target/percopy in
#       the target volume) and the mesh cube-h<H> of every H in
#       /target/percopy/meshes: 0.12 = the frozen fixture mesh, any other H
#       generated by benchmarks/cohesive-perf/scripts/gen-meshes.sh (the
#       oracle image's Gmsh)
#   bash crates/akantu-bench/scripts/percopy_campaign.sh run NAME H NP STEPS SOLVER [key=value ...]
#       one run of the Rust driver (the input of c1prep_campaign.sh: the
#       harness's material-cohesive.dat, blocked_node = global, 17-digit
#       energies; SOLVER auto = MUMPS, or eigen / faer / mumps; the driver's
#       own Scotch partition, AKA_SEED = 1, written to partition.csv) with
#       the extra user-section parameters, in /target/percopy/runs/NAME,
#       copied to OUT/NAME; refuses an existing NAME.
#
# env: OUT (~/percopy-results), MEMORY (14g), CPUS (8), RUST_IMAGE
# (akantu-rs-mumps:dev), TVOL (akantu-rs-mpi-target). Thread counts: OMP,
# OpenBLAS, Scotch = 1, OpenBLAS core Haswell (image ENV, D-050).
set -uo pipefail
repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
out="${OUT:-${HOME}/percopy-results}"
memory="${MEMORY:-14g}" cpus="${CPUS:-8}"
image="${RUST_IMAGE:-akantu-rs-mumps:dev}"
tvol="${TVOL:-akantu-rs-mpi-target}"
bin=/target/percopy/release/cohesive_extrinsic
usage() { sed -n '11,27p' "$0"; exit 2; }
check_h() { [[ "$1" =~ ^0\.[0-9]{1,3}$ ]] || { echo "bad H '$1'" >&2; exit 2; }; }
check_n() { [[ "$1" =~ ^[1-9][0-9]{0,6}$ ]] || { echo "bad number '$1'" >&2; exit 2; }; }

stage=${1:-}; shift || true
case "${stage}" in
  setup)
    [ $# -eq 1 ] || usage
    hs=$1
    for h in ${hs}; do check_h "${h}"; done
    cd "${repo}" || exit 1
    AKANTU_RS_MPI_IMAGE="${image}" AKANTU_RS_MPI_TARGET=/target/percopy AKANTU_RS_DOCKER_CPUS="${cpus}" \
      AKANTU_RS_DOCKER_MEMORY="${memory}" scripts/mpi/in-docker.sh cargo build --release \
      -p akantu-bench --features mpi,scotch,mumps --locked --bin cohesive_extrinsic || exit 1
    docker run --rm -u 0 -v "${tvol}:/target" "${image}" sh -c \
      "mkdir -p /target/percopy/meshes /target/percopy/runs && chmod a+rwX /target/percopy /target/percopy/meshes /target/percopy/runs" \
      || exit 1
    for h in ${hs}; do
      if [ "${h}" = "0.12" ]; then
        docker run --rm -i -u 0 -v "${tvol}:/target" "${image}" sh -c \
          "cat > /target/percopy/meshes/cube-h0.12.msh && chmod a+r /target/percopy/meshes/cube-h0.12.msh" \
          < fixtures/perf_cohesive/meshes/cube-h0.12.msh || exit 1
      else
        bash benchmarks/cohesive-perf/scripts/gen-meshes.sh "${h}" || exit 1
        # shellcheck source=../../../benchmarks/cohesive-perf/scripts/common.sh
        . benchmarks/cohesive-perf/scripts/common.sh
        docker run --rm -u 0 -v "${PERF_VOLUME}:/perf:ro" -v "${tvol}:/target" "${PERF_IMAGE}" sh -c \
          "cp /perf/meshes/cube-h${h}.msh /target/percopy/meshes/ && chmod a+r /target/percopy/meshes/cube-h${h}.msh" \
          || exit 1
      fi
    done
    docker run --rm -v "${tvol}:/target:ro" "${image}" sh -c \
      "sha256sum /target/percopy/meshes/*.msh ${bin}"
    ;;
  run)
    [ $# -ge 5 ] || usage
    name=$1 h=$2 np=$3 steps=$4 solver=$5; shift 5
    [[ "${name}" =~ ^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$ ]] || { echo "bad NAME" >&2; exit 2; }
    check_h "${h}"; check_n "${np}"; check_n "${steps}"
    [[ "${solver}" =~ ^(auto|eigen|faer|mumps)$ ]] || { echo "bad SOLVER '${solver}'" >&2; exit 2; }
    for kv in "$@"; do
      [[ "${kv}" =~ ^(rust_[a-z_]+|export_partition)=[A-Za-z0-9._,:/+-]+$ ]] \
        || { echo "bad parameter '${kv}' (rust_*=value or export_partition=value)" >&2; exit 2; }
    done
    [ -e "${out}/${name}" ] && { echo "refused: ${out}/${name} exists" >&2; exit 3; }
    rd="/target/percopy/runs/${name}"
    mkdir -p "${out}/${name}"
    echo "$(date -u +%FT%TZ) start ${name} h=${h} np=${np} steps=${steps} solver=${solver} $*" | tee -a "${out}/schedule.log"
    docker run --rm --init --name "percopy-${name}" \
      --memory "${memory}" --memory-swap "${memory}" --cpus "${cpus}" --shm-size 4g \
      -v "${tvol}:/target" -v "${repo}:/src:ro" -w /src "${image}" \
      bash /src/crates/akantu-bench/scripts/c1prep_campaign.sh --rust-run \
      "${rd}" "${np}" "${steps}" "/target/percopy/meshes/cube-h${h}.msh" - "${solver}" "${bin}" "$@" \
      > "${out}/${name}/launch.log" 2>&1
    dexit=$?
    docker run --rm -u "$(id -u):$(id -g)" -v "${tvol}:/vol:ro" -v "${out}/${name}:/out" "${image}" \
      sh -c "cp -r /vol/percopy/runs/${name}/. /out/"
    echo "${dexit}" > "${out}/${name}/docker_exit"
    rexit=$(cat "${out}/${name}/exit" 2>/dev/null || echo missing)
    echo "$(date -u +%FT%TZ) end ${name}: docker ${dexit}, driver exit ${rexit}" | tee -a "${out}/schedule.log"
    [ "${dexit}" = 0 ] && [ "${rexit}" = 0 ]
    ;;
  *) usage ;;
esac
