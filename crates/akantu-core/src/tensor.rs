//! Small dense vectors and matrices (decision record D-011).
//!
//! * [`Vector<N>`] = `[Real; N]`.
//! * [`Matrix<R, C>`] = `[[Real; R]; C]`, **column-major**: `m[j][i]` is
//!   row `i`, column `j`. This is exactly Eigen's default storage, so a tuple
//!   of an `Array<Real>` with `nb_component = R * C` can be viewed in place
//!   as a matrix ([`as_matrix`]) with the same element order as upstream's
//!   `make_view(array, R, C)`. Always use [`MatrixExt::at`] /
//!   [`MatrixExt::at_mut`] to avoid row/column confusion.
//! * [`MatrixX`] is the dynamically sized counterpart (also column-major).
//!
//! # Floating-point contract
//!
//! Operations reproduce the results of the corresponding upstream Eigen 3.4.0
//! expression **bit for bit** in the oracle's `strict` configuration
//! (`-O2 -ffp-contract=off -DEIGEN_DONT_VECTORIZE`), with the evaluation order
//! of [`crate::eigen_order`]: fixed-size types follow Eigen's fixed-size
//! (compile-time) rules, [`MatrixX`] follows Eigen's dynamic-size rules —
//! choose the type that matches the upstream code being ported
//! (`Matrix<Real, 3, 3>` vs `Matrix<Real>` / dynamic `Map`). Evidence:
//! `crates/akantu-linalg/tests/dense_parity.rs` against fixtures generated by
//! `oracle/probes/dense/`. Never fused (`mul_add`), never re-associated.
//!
//! | Operation | Fixed-size (`Matrix<R, C>`) | Dynamic (`MatrixX`) | Parity |
//! |---|---|---|---|
//! | product | Eigen's route ([`crate::eigen_gebp`]): coefficient-based (halving tree over a depth `≤ 27`), GEMV, outer, or `gebp` (incl. `GemmProduct`s with `rows+cols+depth < 20`, which are coefficient-based) | `rows+cols+depth < 20`: coefficient-based, sequential from the first term; single row/column: GEMV; otherwise `gebp` with depth blocking | bit-exact |
//! | `dot`, `norm`, `trace`, `sum`, `double_dot` | halving tree | – | bit-exact |
//! | `det` | closed forms `N ≤ 4`; partial-pivot LU for `N > 4` (`N ≤ 16`) | partial-pivot LU (`n ≤ 16`) | bit-exact |
//! | `inverse` | closed forms `N ≤ 4`; LU + triangular solves for `N > 4` | LU + triangular solves | bit-exact for the sizes covered by the fixtures (`n ≤ 8`); larger sizes follow the same algorithm |
//!
//! [`SquareMatrixExt::inverse`] / [`MatrixX::inverse`] return an error for an
//! exactly singular matrix (zero determinant / zero pivot); the `_unchecked`
//! variants reproduce upstream exactly (`inf`/`NaN`, no error).
//! Eigen-decompositions live in `akantu-linalg::dense`.

use crate::error::{Error, Result};
use crate::types::{Real, checked_len};

/// Fixed-size vector.
pub type Vector<const N: usize> = [Real; N];

/// Fixed-size column-major matrix: `m[col][row]`.
pub type Matrix<const R: usize, const C: usize> = [[Real; R]; C];

/// View a flat slice of length `R * C` as a column-major matrix (zero-copy).
/// `R = 0` and/or `C = 0` are valid (point elements have natural dimension
/// 0): the slice must then be empty.
pub fn as_matrix<const R: usize, const C: usize>(s: &[Real]) -> Result<&Matrix<R, C>> {
    matrix_view::<Real, R, C>(s, "as_matrix")
}

/// Mutable version of [`as_matrix`].
pub fn as_matrix_mut<const R: usize, const C: usize>(s: &mut [Real]) -> Result<&mut Matrix<R, C>> {
    matrix_view_mut::<Real, R, C>(s, "as_matrix_mut")
}

/// [`as_matrix`] for any element type: the column-major `R × C` view
/// `m[col][row]` of a slice of `R * C` values (upstream `make_view<R, C>`
/// gives a `MatrixProxy<T, R, C>` for every `T`, `test_array.cc`
/// `ViewMatrix*` instantiates it for `Real`, `UInt` and a class type).
pub fn as_matrix_of<T, const R: usize, const C: usize>(s: &[T]) -> Result<&[[T; R]; C]> {
    matrix_view::<T, R, C>(s, "as_matrix_of")
}

/// Mutable version of [`as_matrix_of`].
pub fn as_matrix_of_mut<T, const R: usize, const C: usize>(
    s: &mut [T],
) -> Result<&mut [[T; R]; C]> {
    matrix_view_mut::<T, R, C>(s, "as_matrix_of_mut")
}

fn matrix_view<'a, T, const R: usize, const C: usize>(
    s: &'a [T],
    context: &'static str,
) -> Result<&'a [[T; R]; C]> {
    let err = || Error::DimensionMismatch {
        context,
        expected: R * C,
        got: s.len(),
    };
    if R == 0 {
        if !s.is_empty() {
            return Err(err());
        }
        let z: &[[T; R]] = zero_row_matrix::<T, R, C>();
        return z.try_into().map_err(|_| err());
    }
    let (cols, rest) = s.as_chunks::<R>();
    if !rest.is_empty() || cols.len() != C {
        return Err(err());
    }
    cols.try_into().map_err(|_| err())
}

fn matrix_view_mut<'a, T, const R: usize, const C: usize>(
    s: &'a mut [T],
    context: &'static str,
) -> Result<&'a mut [[T; R]; C]> {
    let len = s.len();
    let err = || Error::DimensionMismatch {
        context,
        expected: R * C,
        got: len,
    };
    if R == 0 {
        if len != 0 {
            return Err(err());
        }
        return zero_row_matrix::<T, R, C>().try_into().map_err(|_| err());
    }
    let (cols, rest) = s.as_chunks_mut::<R>();
    if !rest.is_empty() || cols.len() != C {
        return Err(err());
    }
    cols.try_into().map_err(|_| err())
}

/// `C` zero-length columns as a mutable slice without allocation (a `Vec` of
/// a zero-sized type never allocates, so leaking it is free; `[T; 0]` is
/// zero-sized for every `T`). Only called with `R == 0`.
fn zero_row_matrix<'a, T, const R: usize, const C: usize>() -> &'a mut [[T; R]] {
    debug_assert_eq!(R, 0);
    // `R == 0`: the closure is never called (an empty array has no element)
    let v: Vec<[T; R]> = (0..C)
        .map(|_| std::array::from_fn(|_| unreachable!("only called with R == 0")))
        .collect();
    v.leak()
}

