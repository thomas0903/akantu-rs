use crate::eigen_order as eo;

/// Operations on [`Vector`] (Eigen fixed-size semantics).
pub trait VectorExt<const N: usize> {
    /// Zero vector.
    fn zeros() -> Self;
    /// `a.dot(b)` (halving tree).
    fn dot(&self, other: &Self) -> Real;
    /// `squaredNorm()` (halving tree of squares).
    fn squared_norm(&self) -> Real;
    /// Euclidean norm `sqrt(squaredNorm())` (upstream `.norm()`).
    fn norm(&self) -> Real;
    /// Entry-wise sum.
    fn add(&self, other: &Self) -> Self;
    /// Entry-wise difference.
    fn sub(&self, other: &Self) -> Self;
    /// Scaling `v_i · alpha`.
    fn scale(&self, alpha: Real) -> Self;
    /// Entry-wise quotient `v_i / alpha` (Eigen `v / alpha`: a true
    /// division, not a multiplication by `1 / alpha`).
    fn div(&self, alpha: Real) -> Self;
    /// Entry-wise product (Eigen `v.array() * w.array()`, `cwiseProduct`).
    fn cwise_mul(&self, other: &Self) -> Self;
}

impl<const N: usize> VectorExt<N> for Vector<N> {
    #[inline]
    fn zeros() -> Self {
        [0.0; N]
    }

    #[inline]
    fn dot(&self, other: &Self) -> Real {
        eo::sum(N, eo::PRODUCT_TERM_COST, true, &|i| self[i] * other[i])
    }

    #[inline]
    fn squared_norm(&self) -> Real {
        eo::sum(N, eo::UNARY_TERM_COST, true, &|i| self[i] * self[i])
    }

    #[inline]
    fn norm(&self) -> Real {
        self.squared_norm().sqrt()
    }

    #[inline]
    fn add(&self, other: &Self) -> Self {
        std::array::from_fn(|i| self[i] + other[i])
    }

    #[inline]
    fn sub(&self, other: &Self) -> Self {
        std::array::from_fn(|i| self[i] - other[i])
    }

    #[inline]
    fn scale(&self, alpha: Real) -> Self {
        std::array::from_fn(|i| self[i] * alpha)
    }

    #[inline]
    fn div(&self, alpha: Real) -> Self {
        std::array::from_fn(|i| self[i] / alpha)
    }

    #[inline]
    fn cwise_mul(&self, other: &Self) -> Self {
        std::array::from_fn(|i| self[i] * other[i])
    }
}

/// Operations on [`Matrix`] (Eigen fixed-size semantics).
pub trait MatrixExt<const R: usize, const C: usize> {
    /// Zero matrix.
    fn zeros() -> Self;
    /// Build from row-major nested arrays (convenient for literals/tests).
    fn from_rows(rows: [[Real; C]; R]) -> Self;
    /// Entry at row `i`, column `j`.
    fn at(&self, i: usize, j: usize) -> Real;
    /// Mutable entry at row `i`, column `j`.
    fn at_mut(&mut self, i: usize, j: usize) -> &mut Real;
    /// Flat column-major data.
    fn as_flat(&self) -> &[Real];
    /// Transpose.
    fn transpose(&self) -> Matrix<C, R>;
    /// `self * rhs` (Eigen product of fixed-size operands, route and order
    /// of [`crate::eigen_gebp`]).
    fn matmul<const K: usize>(&self, rhs: &Matrix<C, K>) -> Matrix<R, K>;
    /// `self.transpose() * rhs` without forming the transpose (a row-major
    /// left operand for Eigen's kernels).
    fn tr_matmul<const K: usize>(&self, rhs: &Matrix<R, K>) -> Matrix<C, K>;
    /// `self * v` (`v` a compile-time column vector).
    fn mul_vec(&self, v: &Vector<C>) -> Vector<R>;
    /// Entry-wise sum.
    fn add(&self, other: &Self) -> Self;
    /// Entry-wise difference.
    fn sub(&self, other: &Self) -> Self;
    /// Scaling `m_ij · alpha`.
    fn scale(&self, alpha: Real) -> Self;
    /// Entry-wise quotient `m_ij / alpha` (Eigen `m / alpha`).
    fn div(&self, alpha: Real) -> Self;
    /// Entry-wise product (Eigen `cwiseProduct`).
    fn cwise_mul(&self, other: &Self) -> Self;
    /// Sum of all entries (`sum()`, halving tree over column-major order).
    fn sum(&self) -> Real;
    /// `squaredNorm()` (Frobenius², halving tree, column-major order).
    fn squared_norm(&self) -> Real;
    /// Frobenius norm (upstream `.norm()` on a matrix).
    fn norm(&self) -> Real;
    /// Upstream `doubleDot`: `cwiseProduct(other).sum()`.
    fn double_dot(&self, other: &Self) -> Real;
}

impl<const R: usize, const C: usize> MatrixExt<R, C> for Matrix<R, C> {
    #[inline]
    fn zeros() -> Self {
        [[0.0; R]; C]
    }

    fn from_rows(rows: [[Real; C]; R]) -> Self {
        std::array::from_fn(|j| std::array::from_fn(|i| rows[i][j]))
    }

    #[inline(always)]
    fn at(&self, i: usize, j: usize) -> Real {
        self[j][i]
    }

    #[inline(always)]
    fn at_mut(&mut self, i: usize, j: usize) -> &mut Real {
        &mut self[j][i]
    }

    #[inline]
    fn as_flat(&self) -> &[Real] {
        self.as_flattened()
    }

    #[inline]
    fn transpose(&self) -> Matrix<C, R> {
        std::array::from_fn(|i| std::array::from_fn(|j| self[j][i]))
    }

    #[inline]
    fn matmul<const K: usize>(&self, rhs: &Matrix<C, K>) -> Matrix<R, K> {
        let mut out = [[0.0; R]; K];
        eval_routed(
            const { route(&ProductShape::fixed(R, C, K)) },
            R,
            C,
            K,
            &|i, k| self[k][i],
            &|k, j| rhs[j][k],
            out.as_flattened_mut(),
        );
        out
    }

    #[inline]
    fn tr_matmul<const K: usize>(&self, rhs: &Matrix<R, K>) -> Matrix<C, K> {
        let mut out = [[0.0; C]; K];
        eval_routed(
            const { route(&ProductShape::fixed(C, R, K).lhs_transposed()) },
            C,
            R,
            K,
            &|i, k| self[i][k],
            &|k, j| rhs[j][k],
            out.as_flattened_mut(),
        );
        out
    }

    #[inline]
    fn mul_vec(&self, v: &Vector<C>) -> Vector<R> {
        let mut out = [0.0; R];
        eval_routed(
            const { route(&ProductShape::fixed(R, C, 1)) },
            R,
            C,
            1,
            &|i, k| self[k][i],
            &|k, _| v[k],
            &mut out,
        );
        out
    }

    #[inline]
    fn add(&self, other: &Self) -> Self {
        std::array::from_fn(|j| std::array::from_fn(|i| self[j][i] + other[j][i]))
    }

    #[inline]
    fn sub(&self, other: &Self) -> Self {
        std::array::from_fn(|j| std::array::from_fn(|i| self[j][i] - other[j][i]))
    }

    #[inline]
    fn scale(&self, alpha: Real) -> Self {
        std::array::from_fn(|j| std::array::from_fn(|i| self[j][i] * alpha))
    }

    #[inline]
    fn div(&self, alpha: Real) -> Self {
        std::array::from_fn(|j| std::array::from_fn(|i| self[j][i] / alpha))
    }

    #[inline]
    fn cwise_mul(&self, other: &Self) -> Self {
        std::array::from_fn(|j| std::array::from_fn(|i| self[j][i] * other[j][i]))
    }

    fn sum(&self) -> Real {
        let f = self.as_flattened();
        eo::sum(R * C, eo::READ_COST, true, &|l| f[l])
    }

    fn squared_norm(&self) -> Real {
        let f = self.as_flattened();
        eo::sum(R * C, eo::UNARY_TERM_COST, true, &|l| f[l] * f[l])
    }

    fn norm(&self) -> Real {
        self.squared_norm().sqrt()
    }

    fn double_dot(&self, other: &Self) -> Real {
        let (a, b) = (self.as_flattened(), other.as_flattened());
        eo::sum(R * C, eo::PRODUCT_TERM_COST, true, &|l| a[l] * b[l])
    }
}

/// Square-matrix operations (Eigen fixed-size semantics).
pub trait SquareMatrixExt<const N: usize> {
    /// Identity.
    fn identity() -> Self;
    /// Trace (`diagonal().sum()`, halving tree).
    fn trace(&self) -> Real;
    /// Determinant: Eigen's closed forms for `N ≤ 4`, partial-pivot LU
    /// otherwise.
    fn det(&self) -> Real;
    /// Inverse; error if the matrix is exactly singular for the algorithm
    /// (zero determinant in the closed forms, zero pivot in the LU).
    fn inverse(&self) -> Result<Self>
    where
        Self: Sized;
    /// Inverse with upstream semantics (no check: `inf`/`NaN` for singular
    /// input).
    fn inverse_unchecked(&self) -> Self
    where
        Self: Sized;
}

/// Eigen 2×2 determinant `m00·m11 − m10·m01`.
#[inline]
fn det2(m: impl Fn(usize, usize) -> Real) -> Real {
    m(0, 0) * m(1, 1) - m(1, 0) * m(0, 1)
}

/// Eigen 3×3 determinant (expansion along the first row, Eigen order).
#[inline]
fn det3(m: impl Fn(usize, usize) -> Real) -> Real {
    let h = |a: usize, b: usize, c: usize| m(0, a) * (m(1, b) * m(2, c) - m(1, c) * m(2, b));
    h(0, 1, 2) - h(1, 0, 2) + h(2, 0, 1)
}

/// Eigen 4×4 determinant (2×2 minors of the first two columns).
fn det4(m: impl Fn(usize, usize) -> Real) -> Real {
    let d2 = |i0: usize, i1: usize| m(i0, 0) * m(i1, 1) - m(i1, 0) * m(i0, 1);
    // pmadd(a, b, c) = a*b + c (not fused)
    let d3 = |i0: usize, d0: Real, i1: usize, d1: Real, i2: usize, dd2: Real| {
        m(i0, 2) * d0 + ((-m(i1, 2)) * d1 + m(i2, 2) * dd2)
    };
    let (d01, d02, d03, d12, d13, d23) =
        (d2(0, 1), d2(0, 2), d2(0, 3), d2(1, 2), d2(1, 3), d2(2, 3));
    let d3_0 = d3(1, d23, 2, d13, 3, d12);
    let d3_1 = d3(0, d23, 2, d03, 3, d02);
    let d3_2 = d3(0, d13, 1, d03, 3, d01);
    let d3_3 = d3(0, d12, 1, d02, 2, d01);
    ((-m(0, 3)) * d3_0 + m(1, 3) * d3_1) + ((-m(2, 3)) * d3_2 + m(3, 3) * d3_3)
}

/// Closed-form inverse for `n ≤ 4` into `out` (column-major `n × n`);
/// returns the determinant used by the formula (`0` ⇒ singular).
fn closed_form_inverse(n: usize, m: &impl Fn(usize, usize) -> Real, out: &mut [Real]) -> Real {
    let mut set = |i: usize, j: usize, v: Real| out[i + j * n] = v;
    match n {
        0 => 1.0,
        1 => {
            set(0, 0, 1.0 / m(0, 0));
            m(0, 0)
        }
        2 => {
            let det = det2(m);
            let invdet = 1.0 / det;
            set(0, 0, m(1, 1) * invdet);
            set(1, 0, -m(1, 0) * invdet);
            set(0, 1, -m(0, 1) * invdet);
            set(1, 1, m(0, 0) * invdet);
            det
        }
        3 => {
            let cof = |i: usize, j: usize| {
                let (i1, i2, j1, j2) = ((i + 1) % 3, (i + 2) % 3, (j + 1) % 3, (j + 2) % 3);
                m(i1, j1) * m(i2, j2) - m(i1, j2) * m(i2, j1)
            };
            let c0 = [cof(0, 0), cof(1, 0), cof(2, 0)];
            // (cofactors_col0 .* col0).sum(), fixed size 3: t0 + (t1 + t2)
            let det = c0[0] * m(0, 0) + (c0[1] * m(1, 0) + c0[2] * m(2, 0));
            let invdet = 1.0 / det;
            for j in 1..3 {
                for i in 0..3 {
                    // result(i, j) = cofactor(j, i) * invdet
                    set(i, j, cof(j, i) * invdet);
                }
            }
            for (j, c) in c0.iter().enumerate() {
                set(0, j, c * invdet);
            }
            // rows 1, 2 of column 0
            set(1, 0, cof(0, 1) * invdet);
            set(2, 0, cof(0, 2) * invdet);
            det
        }
        4 => {
            let h = |i1: usize, i2: usize, i3: usize, j1: usize, j2: usize, j3: usize| {
                m(i1, j1) * (m(i2, j2) * m(i3, j3) - m(i2, j3) * m(i3, j2))
            };
            let cof = |i: usize, j: usize| {
                let (i1, i2, i3) = ((i + 1) % 4, (i + 2) % 4, (i + 3) % 4);
                let (j1, j2, j3) = ((j + 1) % 4, (j + 2) % 4, (j + 3) % 4);
                h(i1, i2, i3, j1, j2, j3) + h(i2, i3, i1, j1, j2, j3) + h(i3, i1, i2, j1, j2, j3)
            };
            for i in 0..4 {
                for j in 0..4 {
                    // result(i, j) = (-1)^(i+j) cofactor_4x4<j, i>
                    let c = cof(j, i);
                    set(i, j, if (i + j) % 2 == 0 { c } else { -c });
                }
            }
            // det = (col(0) .* row(0)^T).sum(), fixed size 4: (t0+t1)+(t2+t3)
            let r = |j: usize| out[j * 4];
            let det = (m(0, 0) * r(0) + m(1, 0) * r(1)) + (m(2, 0) * r(2) + m(3, 0) * r(3));
            for v in out.iter_mut() {
                *v /= det;
            }
            det
        }
        _ => unreachable!("closed-form inverse only for n <= 4"),
    }
}

impl<const N: usize> SquareMatrixExt<N> for Matrix<N, N> {
    fn identity() -> Self {
        std::array::from_fn(|j| std::array::from_fn(|i| if i == j { 1.0 } else { 0.0 }))
    }

    fn trace(&self) -> Real {
        eo::sum(N, eo::READ_COST, true, &|i| self[i][i])
    }

    fn det(&self) -> Real {
        let m = |i: usize, j: usize| self[j][i];
        match N {
            0 => 1.0,
            1 => m(0, 0),
            2 => det2(m),
            3 => det3(m),
            4 => det4(m),
            _ => {
                let mut lu = self.as_flattened().to_vec();
                lu::det(&mut lu, N, true)
            }
        }
    }

    fn inverse(&self) -> Result<Self> {
        let (inv, singular) = self.inverse_impl();
        if singular {
            return Err(Error::Numerical("inverse of a singular matrix".into()));
        }
        Ok(inv)
    }

    fn inverse_unchecked(&self) -> Self {
        self.inverse_impl().0
    }
}

trait InverseImpl: Sized {
    fn inverse_impl(&self) -> (Self, bool);
}

impl<const N: usize> InverseImpl for Matrix<N, N> {
    fn inverse_impl(&self) -> (Self, bool) {
        let mut inv = [[0.0; N]; N];
        let singular = if N <= 4 {
            // the closed forms write into the result directly (no heap
            // buffer per call)
            let m = |i: usize, j: usize| self[j][i];
            closed_form_inverse(N, &m, inv.as_flattened_mut()) == 0.0
        } else {
            let mut out = vec![0.0; N * N];
            let mut a = self.as_flattened().to_vec();
            let singular = lu::inverse(&mut a, N, &mut out);
            for (j, col) in inv.iter_mut().enumerate() {
                col.copy_from_slice(&out[j * N..(j + 1) * N]);
            }
            singular
        };
        (inv, singular)
    }
}

/// Partial-pivot LU and triangular solves with Eigen 3.4.0's evaluation
/// order (unblocked LU for `n ≤ 16`, `PartialPivLU::_solve_impl`,
/// `triangular_solve_matrix` with 4-wide panels).
mod lu {
    use super::Real;
    use crate::eigen_order as eo;

    /// Eigen `SmallPanelWidth` of the triangular solver
    /// (`max(gebp mr, gebp nr)` = 4 without vectorisation).
    const PANEL: usize = 4;

    /// In-place LU with partial pivoting of the column-major `n × n` matrix
    /// `a`; returns the row transpositions and their count. Pivot: first
    /// index of the largest `|a_ik|` (strict `>`), whole-row swaps, column
    /// scaled by division, rank-1 update `a_ij − l_i·u_j`.
    pub(super) fn factor(a: &mut [Real], n: usize) -> (Vec<usize>, usize, bool) {
        let mut transpositions = vec![0; n];
        let mut nb_transpositions = 0;
        let mut zero_pivot = false;
        for k in 0..n {
            let mut piv = k;
            let mut biggest = a[k + k * n].abs();
            for i in k + 1..n {
                let s = a[i + k * n].abs();
                if s > biggest {
                    biggest = s;
                    piv = i;
                }
            }
            transpositions[k] = piv;
            if biggest != 0.0 {
                if piv != k {
                    for j in 0..n {
                        a.swap(k + j * n, piv + j * n);
                    }
                    nb_transpositions += 1;
                }
                let d = a[k + k * n];
                for i in k + 1..n {
                    a[i + k * n] /= d;
                }
            } else {
                zero_pivot = true;
            }
            for j in k + 1..n {
                let u = a[k + j * n];
                for i in k + 1..n {
                    a[i + j * n] -= a[i + k * n] * u;
                }
            }
        }
        (transpositions, nb_transpositions, zero_pivot)
    }

    /// `PartialPivLU::determinant()`: `±1 · diagonal().prod()` (product order
    /// per compile-time / run-time size).
    pub(super) fn det(a: &mut [Real], n: usize, fixed: bool) -> Real {
        let (_, nb_transpositions, _) = factor(a, n);
        let sign = if nb_transpositions % 2 == 1 {
            -1.0
        } else {
            1.0
        };
        sign * eo::prod(n, eo::READ_COST, fixed, &|i| a[i + i * n])
    }

    /// `PartialPivLU::inverse()` = solve with the identity: permute, unit
    /// lower solve, upper solve (Eigen `triangular_solve_matrix`, 4-wide
    /// panels, trailing updates accumulated from `+0`). Returns `true` for a
    /// zero pivot (singular).
    pub(super) fn inverse(a: &mut [Real], n: usize, out: &mut [Real]) -> bool {
        let (tr, _, zero_pivot) = factor(a, n);
        out.fill(0.0);
        for i in 0..n {
            out[i + i * n] = 1.0;
        }
        // dst = P * I: apply the transpositions in order
        for (k, &p) in tr.iter().enumerate() {
            if p != k {
                for j in 0..n {
                    out.swap(k + j * n, p + j * n);
                }
            }
        }
        solve_lower_unit(a, n, out, n);
        solve_upper(a, n, out, n);
        zero_pivot
    }

    /// `L X = B` in place (`L` unit lower, column-major `n × n`; `B` has
    /// `cols` columns).
    fn solve_lower_unit(lu: &[Real], n: usize, b: &mut [Real], cols: usize) {
        let mut k1 = 0;
        while k1 < n {
            let pw = PANEL.min(n - k1);
            for k in 0..pw {
                let i = k1 + k;
                let rs = pw - k - 1;
                let s = i + 1;
                for j in 0..cols {
                    // otherij *= 1 (unit diagonal)
                    let bij = b[i + j * n];
                    for i3 in 0..rs {
                        b[s + i3 + j * n] -= bij * lu[s + i3 + i * n];
                    }
                }
            }
            // trailing rows below the panel: other -= L21 * B1 (acc from +0)
            for j in 0..cols {
                for t in k1 + pw..n {
                    let mut acc = 0.0;
                    for k in k1..k1 + pw {
                        acc += lu[t + k * n] * b[k + j * n]; // IEEE addition is commutative: same bits as `t + acc`
                    }
                    b[t + j * n] += -acc;
                }
            }
            k1 += pw;
        }
    }

    /// `U X = B` in place (`U` upper with diagonal, column-major).
    fn solve_upper(lu: &[Real], n: usize, b: &mut [Real], cols: usize) {
        let mut k1 = 0;
        while k1 < n {
            let pw = PANEL.min(n - k1);
            for k in 0..pw {
                let i = n - k1 - k - 1;
                let rs = pw - k - 1;
                let s = i - rs;
                let a = 1.0 / lu[i + i * n];
                for j in 0..cols {
                    b[i + j * n] *= a;
                    let bij = b[i + j * n];
                    for i3 in 0..rs {
                        b[s + i3 + j * n] -= bij * lu[s + i3 + i * n];
                    }
                }
            }
            // trailing rows above the panel
            let start_block = n - k1 - pw;
            for j in 0..cols {
                for t in 0..start_block {
                    let mut acc = 0.0;
                    for k in start_block..start_block + pw {
                        acc += lu[t + k * n] * b[k + j * n]; // IEEE addition is commutative: same bits as `t + acc`
                    }
                    b[t + j * n] += -acc;
                }
            }
            k1 += pw;
        }
    }
}

/// Dynamically sized column-major matrix (upstream `MatrixXr`, dynamic
/// `Map`s). Arithmetic follows Eigen's **dynamic-size** rules.
#[derive(Clone, Debug, PartialEq, Default)]
pub struct MatrixX {
    rows: usize,
    cols: usize,
    data: Vec<Real>,
}

impl MatrixX {
    /// Checked `rows × cols` zero matrix (overflow / allocation refusal →
    /// [`Error::CapacityExceeded`]).
    pub fn try_zeros(rows: usize, cols: usize) -> Result<Self> {
        let n = checked_len(rows, cols, "MatrixX storage")?;
        let mut data = Vec::new();
        data.try_reserve_exact(n)
            .map_err(|_| Error::CapacityExceeded {
                what: "MatrixX storage",
                requested: (n as u128) * 8,
                limit: isize::MAX as u128,
            })?;
        data.resize(n, 0.0);
        Ok(Self { rows, cols, data })
    }

    /// `rows × cols` zero matrix (`0 × n` and `n × 0` allowed).
    ///
    /// # Panics
    /// On size overflow / allocation refusal (use [`MatrixX::try_zeros`]).
    #[must_use]
    #[track_caller]
    pub fn zeros(rows: usize, cols: usize) -> Self {
        match Self::try_zeros(rows, cols) {
            Ok(m) => m,
            Err(e) => panic!("MatrixX::zeros: {e}"),
        }
    }

    /// `n × n` identity.
    #[must_use]
    pub fn identity(n: usize) -> Self {
        let mut m = Self::zeros(n, n);
        for i in 0..n {
            m.data[i + i * n] = 1.0;
        }
        m
    }

    /// Wrap column-major data (checked `rows * cols`).
    pub fn from_col_major(rows: usize, cols: usize, data: Vec<Real>) -> Result<Self> {
        let n = checked_len(rows, cols, "MatrixX storage")?;
        if data.len() != n {
            return Err(Error::DimensionMismatch {
                context: "MatrixX::from_col_major",
                expected: n,
                got: data.len(),
            });
        }
        Ok(Self { rows, cols, data })
    }

    /// Copy of a fixed-size matrix.
    #[must_use]
    pub fn from_fixed<const R: usize, const C: usize>(m: &Matrix<R, C>) -> Self {
        Self {
            rows: R,
            cols: C,
            data: m.as_flattened().to_vec(),
        }
    }

    /// Number of rows.
    #[must_use]
    pub fn rows(&self) -> usize {
        self.rows
    }

    /// Number of columns.
    #[must_use]
    pub fn cols(&self) -> usize {
        self.cols
    }

    /// Entry `(i, j)`.
    #[inline(always)]
    #[must_use]
    #[track_caller]
    pub fn at(&self, i: usize, j: usize) -> Real {
        assert!(i < self.rows && j < self.cols, "MatrixX::at out of bounds");
        self.data[i + j * self.rows]
    }

    /// Mutable entry `(i, j)`.
    #[inline(always)]
    #[track_caller]
    pub fn at_mut(&mut self, i: usize, j: usize) -> &mut Real {
        assert!(
            i < self.rows && j < self.cols,
            "MatrixX::at_mut out of bounds"
        );
        &mut self.data[i + j * self.rows]
    }

    /// Column-major data.
    #[must_use]
    pub fn as_slice(&self) -> &[Real] {
        &self.data
    }

    /// Mutable column-major data.
    pub fn as_mut_slice(&mut self) -> &mut [Real] {
        &mut self.data
    }

    /// Column `c` (upstream `M(c)` / `M.col(c)`: Akantu's matrix plugin
    /// makes `operator()(c)` a column), `None` if out of range.
    #[must_use]
    pub fn col(&self, c: usize) -> Option<&[Real]> {
        (c < self.cols).then(|| &self.data[c * self.rows..(c + 1) * self.rows])
    }

    /// Mutable column `c`.
    pub fn col_mut(&mut self, c: usize) -> Option<&mut [Real]> {
        (c < self.cols).then(|| &mut self.data[c * self.rows..(c + 1) * self.rows])
    }

    /// Columns in order (upstream range-for over a matrix iterates
    /// columns): `cols` slices of `rows` values each, so a matrix with zero
    /// rows yields `cols` empty columns.
    pub fn columns(&self) -> impl ExactSizeIterator<Item = &[Real]> + '_ {
        let rows = self.rows;
        (0..self.cols).map(move |c| &self.data[c * rows..(c + 1) * rows])
    }

    /// Set every entry to `value` (upstream `set(value)`).
    pub fn fill(&mut self, value: Real) {
        self.data.fill(value);
    }

    fn check_same_shape(&self, other: &MatrixX, context: &'static str) -> Result<()> {
        if (self.rows, self.cols) == (other.rows, other.cols) {
            Ok(())
        } else {
            Err(Error::DimensionMismatch {
                context,
                expected: self.data.len(),
                got: other.data.len(),
            })
        }
    }

    /// Entry-wise sum (shapes must agree).
    pub fn add(&self, other: &MatrixX) -> Result<MatrixX> {
        self.check_same_shape(other, "MatrixX::add")?;
        let data = self
            .data
            .iter()
            .zip(&other.data)
            .map(|(a, b)| a + b)
            .collect();
        Ok(Self { data, ..*self })
    }

    /// Entry-wise difference (shapes must agree).
    pub fn sub(&self, other: &MatrixX) -> Result<MatrixX> {
        self.check_same_shape(other, "MatrixX::sub")?;
        let data = self
            .data
            .iter()
            .zip(&other.data)
            .map(|(a, b)| a - b)
            .collect();
        Ok(Self { data, ..*self })
    }

    /// Scaling `m_ij · alpha`.
    #[must_use]
    pub fn scale(&self, alpha: Real) -> MatrixX {
        let data = self.data.iter().map(|a| a * alpha).collect();
        Self { data, ..*self }
    }

    /// Entry-wise quotient `m_ij / alpha` (Eigen `m / alpha`).
    #[must_use]
    pub fn div(&self, alpha: Real) -> MatrixX {
        let data = self.data.iter().map(|a| a / alpha).collect();
        Self { data, ..*self }
    }

    /// Entry-wise product (Eigen `cwiseProduct`, shapes must agree).
    pub fn cwise_mul(&self, other: &MatrixX) -> Result<MatrixX> {
        self.check_same_shape(other, "MatrixX::cwise_mul")?;
        let data = self
            .data
            .iter()
            .zip(&other.data)
            .map(|(a, b)| a * b)
            .collect();
        Ok(Self { data, ..*self })
    }

    /// Transpose.
    #[must_use]
    pub fn transpose(&self) -> Self {
        let mut t = Self::zeros(self.cols, self.rows);
        for j in 0..self.cols {
            for i in 0..self.rows {
                t.data[j + i * self.cols] = self.data[i + j * self.rows];
            }
        }
        t
    }

    /// `self * rhs` with Eigen's dynamic-size product rules
    /// ([`crate::eigen_gebp`], bit-exact with the strict oracle build):
    /// * empty depth / result: zeros;
    /// * `depth + rows + cols < 20`: coefficient-based, sequential from the
    ///   first term;
    /// * a result with one column: column-major GEMV (depth blocks of 16 from
    ///   depth 128); one row: row-major GEMV; `1 × 1`: inner product
    ///   added to `+0`;
    /// * otherwise `gebp` (even/odd chains in 4-column panels for depth
    ///   `≥ 8`, depth blocks above 408 when `max(rows, cols, depth) ≥ 48`).
    ///
    /// `a.transpose().matmul(b)` models a *materialised* transpose
    /// (`Matrix<Real> at = a.transpose(); at * b`); use
    /// [`MatrixX::tr_matmul`] for upstream's `a.transpose() * b`, which can
    /// differ when the result is a vector.
    pub fn matmul(&self, rhs: &MatrixX) -> Result<MatrixX> {
        if self.cols != rhs.rows {
            return Err(Error::DimensionMismatch {
                context: "MatrixX::matmul",
                expected: self.cols,
                got: rhs.rows,
            });
        }
        let (rows, cols, depth) = (self.rows, rhs.cols, self.cols);
        let mut out = Self::try_zeros(rows, cols)?;
        eval_product(
            &ProductShape::dynamic(rows, depth, cols),
            &|i, k| self.data[i + k * rows],
            &|k, j| rhs.data[k + j * depth],
            &mut out.data,
        );
        Ok(out)
    }

    /// `self.transpose() * rhs` (upstream `a.transpose() * b` on dynamic
    /// matrices: a row-major left operand for Eigen's kernels) without
    /// forming the transpose. Same rules as [`MatrixX::matmul`].
    pub fn tr_matmul(&self, rhs: &MatrixX) -> Result<MatrixX> {
        if self.rows != rhs.rows {
            return Err(Error::DimensionMismatch {
                context: "MatrixX::tr_matmul",
                expected: self.rows,
                got: rhs.rows,
            });
        }
        let (rows, cols, depth) = (self.cols, rhs.cols, self.rows);
        let mut out = Self::try_zeros(rows, cols)?;
        eval_product(
            &ProductShape::dynamic(rows, depth, cols).lhs_transposed(),
            &|i, k| self.data[k + i * depth],
            &|k, j| rhs.data[k + j * depth],
            &mut out.data,
        );
        Ok(out)
    }

    /// Determinant (Eigen dynamic: partial-pivot LU, `1` for `0 × 0`).
    /// Bit-exact for `n ≤ 16` (Eigen switches to a blocked LU above).
    pub fn det(&self) -> Result<Real> {
        self.check_square("MatrixX::det")?;
        if self.rows == 0 {
            return Ok(1.0);
        }
        let mut lu = self.data.clone();
        Ok(lu::det(&mut lu, self.rows, false))
    }

    /// Inverse (Eigen dynamic: partial-pivot LU + triangular solves, also for
    /// `n ≤ 4`); error for a zero pivot.
    pub fn inverse(&self) -> Result<MatrixX> {
        let (inv, singular) = self.inverse_impl()?;
        if singular {
            return Err(Error::Numerical("inverse of a singular matrix".into()));
        }
        Ok(inv)
    }

    /// Inverse with upstream semantics (no singularity check).
    pub fn inverse_unchecked(&self) -> Result<MatrixX> {
        Ok(self.inverse_impl()?.0)
    }

    fn inverse_impl(&self) -> Result<(MatrixX, bool)> {
        self.check_square("MatrixX::inverse")?;
        let n = self.rows;
        let mut out = Self::try_zeros(n, n)?;
        let mut a = self.data.clone();
        let singular = lu::inverse(&mut a, n, &mut out.data);
        Ok((out, singular))
    }

    fn check_square(&self, context: &'static str) -> Result<()> {
        if self.rows != self.cols {
            return Err(Error::DimensionMismatch {
                context,
                expected: self.rows,
                got: self.cols,
            });
        }
        Ok(())
    }
}

