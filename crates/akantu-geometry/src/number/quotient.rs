//! `Quotient<MP_Float>`: exact rationals `num / den` **without**
//! normalisation (CGAL 5.6.2).
//!
//! The numerator/denominator representation produced by each operation is
//! part of the observable behaviour (it determines `to_double`), so every
//! operation reproduces CGAL's formula and its `simplify_quotient` call
//! (`num.exp -= den.exp; den.exp = 0` for `MP_Float`) exactly:
//!
//! | operation | CGAL | simplify |
//! |---|---|---|
//! | `q + r`, `q - r` | `num = num·r.den ± r.num·den; den = den·r.den` | yes |
//! | `q · r` | `num = num·r.num; den = den·r.den` | yes |
//! | `q / r` | `num = num·r.den; den = den·r.num` | yes |
//! | `q ± n`, `q · n`, `q / n` (`n` an `MP_Float` or `int`) | `num ± n·den`, `num·n`, `den·n` | no |
//! | `-q` | `(-num, den)` | — |
//!
//! Binary operators of the C++ class are generated by Boost.Operators from
//! the compound assignments with the left operand copied first
//! (`T nrv(lhs); nrv op= rhs;`); for the commutative mixed forms
//! `n + q`, `n · q` the copy is of the quotient (`nrv(q); nrv op= n`).

use std::cmp::Ordering;

use akantu_core::{Error, Result};

use super::mp_float::{MpFloat, ldexp_one};

/// CGAL `Quotient<MP_Float>`.
#[derive(Clone, Debug)]
pub struct Quotient {
    num: MpFloat,
    den: MpFloat,
}

/// CGAL `simplify_quotient(MP_Float&, MP_Float&)`.
fn simplify(num: &mut MpFloat, den: &mut MpFloat) {
    let e = den.min_exp();
    num.shift_exp(e);
    den.shift_exp(e);
}

impl Quotient {
    /// `Quotient(num, den)` (CGAL precondition `den != 0`).
    ///
    /// # Errors
    /// A zero denominator.
    pub fn try_new(num: MpFloat, den: MpFloat) -> Result<Self> {
        if den.is_zero() {
            return Err(Error::InvalidArgument("Quotient: zero denominator".into()));
        }
        Ok(Self { num, den })
    }

    /// `Quotient(double)`: `Split_double` → `(MP_Float(d), 1)`.
    ///
    /// # Errors
    /// See [`MpFloat::try_from_f64`].
    pub fn try_from_f64(d: f64) -> Result<Self> {
        Ok(Self {
            num: MpFloat::try_from_f64(d)?,
            den: MpFloat::from_i32(1),
        })
    }

    /// `Quotient(int)`: `(MP_Float(i), MP_Float(1))`.
    #[must_use]
    pub fn from_i32(i: i32) -> Self {
        Self {
            num: MpFloat::from_i32(i),
            den: MpFloat::from_i32(1),
        }
    }

    /// `Quotient(MP_Float)`: `(n, 1)`.
    #[must_use]
    pub fn from_mp(n: MpFloat) -> Self {
        Self {
            num: n,
            den: MpFloat::from_i32(1),
        }
    }

    /// Numerator.
    #[must_use]
    pub fn numerator(&self) -> &MpFloat {
        &self.num
    }

    /// Denominator.
    #[must_use]
    pub fn denominator(&self) -> &MpFloat {
        &self.den
    }

    /// `q + r` (with `simplify_quotient`).
    ///
    /// # Errors
    /// `MP_Float` exponent overflow.
    pub fn add(&self, r: &Self) -> Result<Self> {
        let mut num = self.num.mul(&r.den)?.add(&r.num.mul(&self.den)?);
        let mut den = self.den.mul(&r.den)?;
        simplify(&mut num, &mut den);
        Ok(Self { num, den })
    }

    /// `q - r` (with `simplify_quotient`).
    ///
    /// # Errors
    /// `MP_Float` exponent overflow.
    pub fn sub(&self, r: &Self) -> Result<Self> {
        let mut num = self.num.mul(&r.den)?.sub(&r.num.mul(&self.den)?);
        let mut den = self.den.mul(&r.den)?;
        simplify(&mut num, &mut den);
        Ok(Self { num, den })
    }

    /// `q · r` (with `simplify_quotient`).
    ///
    /// # Errors
    /// `MP_Float` exponent overflow.
    pub fn mul(&self, r: &Self) -> Result<Self> {
        let mut num = self.num.mul(&r.num)?;
        let mut den = self.den.mul(&r.den)?;
        simplify(&mut num, &mut den);
        Ok(Self { num, den })
    }

    /// `q / r` (with `simplify_quotient`).
    ///
    /// # Errors
    /// Division by zero (CGAL precondition) or exponent overflow.
    pub fn div(&self, r: &Self) -> Result<Self> {
        if r.num.is_zero() {
            return Err(Error::Numerical("Quotient: division by zero".into()));
        }
        let mut num = self.num.mul(&r.den)?;
        let mut den = self.den.mul(&r.num)?;
        simplify(&mut num, &mut den);
        Ok(Self { num, den })
    }

    /// `q · i` for an `int` (`num *= MP_Float(i)`, no simplify).
    ///
    /// # Errors
    /// Exponent overflow.
    pub fn mul_i32(&self, i: i32) -> Result<Self> {
        Ok(Self {
            num: self.num.mul(&MpFloat::from_i32(i))?,
            den: self.den.clone(),
        })
    }

    /// `q · d` for a `double` (`operator*=(double)`: `Split_double` gives
    /// `(MP_Float(d), 1)`, then `num *= MP_Float(d); den *= 1`; no
    /// simplify). Used e.g. by IGFEM to scale squared sphere radii.
    ///
    /// # Errors
    /// Non-finite `d`, exponent overflow.
    pub fn mul_f64(&self, d: f64) -> Result<Self> {
        Ok(Self {
            num: self.num.mul(&MpFloat::try_from_f64(d)?)?,
            den: self.den.mul(&MpFloat::from_i32(1))?,
        })
    }

    /// `CGAL::square(q)` = `q · q` (Algebraic_structure_traits default).
    ///
    /// # Errors
    /// Exponent overflow.
    pub fn square(&self) -> Result<Self> {
        self.mul(self)
    }

    /// `-q` = `(-num, den)`.
    #[must_use]
    pub fn neg(&self) -> Self {
        Self {
            num: self.num.neg(),
            den: self.den.clone(),
        }
    }

    /// Sign: `sign(num) · sign(den)`.
    #[must_use]
    pub fn sign(&self) -> Ordering {
        sign_mul(self.num.sign(), self.den.sign())
    }

    /// `is_zero`: `num == 0`.
    #[must_use]
    pub fn is_zero(&self) -> bool {
        self.num.is_zero()
    }

    /// CGAL `quotient_cmp` (exact).
    ///
    /// # Errors
    /// Exponent overflow.
    pub fn compare(&self, y: &Self) -> Result<Ordering> {
        let xsign = sign_i(self.num.sign()) * sign_i(self.den.sign());
        let ysign = sign_i(y.num.sign()) * sign_i(y.den.sign());
        if xsign == 0 {
            return Ok(ord(-ysign));
        }
        if ysign == 0 {
            return Ok(ord(xsign));
        }
        if xsign == ysign {
            let msign = sign_i(self.den.sign()) * sign_i(y.den.sign());
            let left = self.num.mul(&y.den)?.mul(&MpFloat::from_i32(msign))?;
            let right = y.num.mul(&self.den)?.mul(&MpFloat::from_i32(msign))?;
            Ok(left.cmp(&right))
        } else {
            Ok(if xsign < ysign {
                Ordering::Less
            } else {
                Ordering::Greater
            })
        }
    }

    /// Exact equality `x.num·y.den == x.den·y.num`.
    ///
    /// # Errors
    /// Exponent overflow.
    pub fn eq_value(&self, y: &Self) -> Result<bool> {
        Ok(self.num.mul(&y.den)? == self.den.mul(&y.num)?)
    }

    /// `CGAL::to_double(Quotient<MP_Float>)` =
    /// `INTERN_MP_FLOAT::to_double(q)`:
    /// `(n.first / d.first) · ldexp(1, n.second − d.second)`.
    ///
    /// # Errors
    /// Exponent overflow.
    pub fn to_double(&self) -> Result<f64> {
        let (nd, ne) = self.num.to_double_exp()?;
        let (dd, de) = self.den.to_double_exp()?;
        let e = ne.checked_sub(de).ok_or_else(|| {
            Error::Numerical("Quotient<MP_Float>::to_double: exponent overflow".into())
        })?;
        Ok((nd / dd) * ldexp_one(e))
    }
}

fn sign_i(o: Ordering) -> i32 {
    match o {
        Ordering::Less => -1,
        Ordering::Equal => 0,
        Ordering::Greater => 1,
    }
}

fn ord(i: i32) -> Ordering {
    i.cmp(&0)
}

fn sign_mul(a: Ordering, b: Ordering) -> Ordering {
    ord(sign_i(a) * sign_i(b))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn q(d: f64) -> Quotient {
        Quotient::try_from_f64(d).unwrap()
    }

    #[test]
    fn exact_field_operations() {
        let a = q(0.1);
        let b = q(0.3);
        let c = a.add(&b).unwrap();
        assert!(c.sub(&b).unwrap().eq_value(&a).unwrap());
        let d = a.div(&b).unwrap();
        assert!(d.mul(&b).unwrap().eq_value(&a).unwrap());
        assert_eq!(a.compare(&b).unwrap(), Ordering::Less);
        assert_eq!(b.neg().compare(&a.neg()).unwrap(), Ordering::Less);
        assert_eq!(q(0.0).sign(), Ordering::Equal);
        assert_eq!(d.neg().sign(), Ordering::Less);
        assert!(a.div(&q(0.0)).is_err());
    }

    #[test]
    fn to_double_of_simple_values() {
        assert_eq!(q(0.25).to_double().unwrap(), 0.25);
        assert_eq!(q(1.0).div(&q(3.0)).unwrap().to_double().unwrap(), 1.0 / 3.0);
        assert_eq!(Quotient::from_i32(-7).to_double().unwrap(), -7.0);
        assert_eq!(q(2.0).mul_i32(3).unwrap().to_double().unwrap(), 6.0);
        let r2 = q(0.09).mul_f64(1.1).unwrap().mul_f64(1.1).unwrap();
        assert_eq!(r2.denominator(), &MpFloat::from_i32(1));
        assert!(r2.compare(&q(0.09 * 1.1 * 1.1)).is_ok());
    }

    #[test]
    fn simplify_moves_the_denominator_exponent() {
        // 1 / 2^-32: den has exp -2 (two zero limbs below), simplified to 0.
        let tiny = q(1.0 / 4_294_967_296.0);
        let r = q(1.0).div(&tiny).unwrap();
        assert_eq!(r.denominator().min_exp(), 0);
        assert_eq!(r.to_double().unwrap(), 4_294_967_296.0);
    }
}
