// akantu-rs verification example (no upstream counterpart; written
// independently of the port as `v89_convergence_off_centre_inclusion`): convergence
// of the IGFEM port of Akantu's (EPFL/LSMS) extra_packages/igfem
// (SolidMechanicsModelIGFEM, MaterialIGFEMElastic, growing-gel mesh
// generation) on a bi-material disk with an off-centre circular inclusion.

//! Off-centre circular inclusion, exact radial solution.
//!
//! Disk of radius `R = 2` centred at `c = (0.0731, −0.0412)` with an
//! inclusion of radius `a = 0.5137` ("gel", `E = 1`, `ν = 0.25`) in the
//! "aggregate" (`E = 10`, `ν = 0.3`), plane strain, radial displacement
//! `u_r(R) = R` (Sukumar et al. 2001 / Fries 2008). Neither the centre nor
//! the radius aligns with the mesh. The problem is restricted to the square
//! `[−4/3, 4/3]²` (structured `n × n` triangulation) with the exact
//! displacement on its boundary; the interface is generated by the
//! growing-gel mesh generation (`SkSphere`, feature `cgal`). The relative L2
//! error is integrated with a 7-point (degree 5) rule on every triangle and
//! IGFEM sub-triangle (quadrangle sub-elements split in two).
//!
//! ```text
//! cargo run --release -p akantu-igfem --features cgal \
//!     --example igfem_off_centre_inclusion -- 256
//! ```
//!
//! prints, for n = 8, 16, …, N (default 64), the L2 error, the element
//! counts and the observed rate. Measured (x86_64, release):
//! rates 1.46, 1.75, 1.84, 1.91, 1.955 for n = 8 → 256,
//! approaching the optimal 2 of linear elements with an `O(h²)` polygonal
//! interface (`docs/NUMERICAL_VALIDATION.md`). The test
//! `review_v89_regressions::off_centre_inclusion_convergence` runs it up to
//! n = 64.

use akantu_core::enums::AnalysisMethod;
use akantu_core::{Element, ElementKind, ElementType, GhostType, Idx, Real, Result};
use akantu_geometry_cgal::SkSphere;
use akantu_igfem::SolidMechanicsModelIgfem;
use akantu_mesh::{Mesh, MeshAccessor, SharedMesh};
use akantu_model::ModelOptions;
use akantu_model::constitutive_law::{ConstitutiveLawSelector, SelectorContext};
use akantu_parser::{ParamValue, Parser};

/// Upstream `test_solid_mechanics_model_igfem` material file: law 0 =
/// aggregate (`E = 10`, `ν = 0.3`), law 1 = gel (`E = 1`, `ν = 0.25`),
/// law 2 = `igfem_elastic` (sub-material 1 = gel, 2 = aggregate).
const DAT: &str = include_str!("../tests/data/upstream/smm_igfem/material.dat");
/// Outer radius of the disk.
const R: Real = 2.0;
/// Centre of the disk and of the inclusion.
const CENTRE: [Real; 2] = [0.0731, -0.0412];
/// Radius of the inclusion.
const RADIUS: Real = 0.5137;
/// Half side of the computational square.
const HALF: Real = 4.0 / 3.0;

/// One mesh level of the study.
#[derive(Clone, Copy, Debug)]
pub struct Level {
    /// Elements per side.
    pub n: usize,
    /// Mesh size (side / n).
    pub h: Real,
    /// Relative L2 error of the displacement.
    pub l2: Real,
    /// Number of `_triangle_3`, `_igfem_triangle_4`, `_igfem_triangle_5`.
    pub counts: [usize; 3],
}

/// Observed rate between two levels.
pub fn rate(coarse: &Level, fine: &Level) -> Real {
    (coarse.l2 / fine.l2).ln() / (coarse.h / fine.h).ln()
}

/// IGFEM elements → law 2; regular elements by the side of their
/// barycenter (inside the inclusion → gel).
#[derive(Debug)]
struct InclusionSelector;

impl ConstitutiveLawSelector for InclusionSelector {
    fn select(&self, ctx: &SelectorContext<'_>, el: Element) -> Result<Option<usize>> {
        if el.ty().kind() == ElementKind::Igfem {
            return Ok(Some(2));
        }
        let b = ctx.mesh.barycenter(el)?;
        let d = ((b[0] - CENTRE[0]).powi(2) + (b[1] - CENTRE[1]).powi(2)).sqrt();
        Ok(Some(usize::from(d < RADIUS)))
    }
}

/// `(λ, μ)` of law `i` (plane-strain values as computed by the law).
fn lame(model: &SolidMechanicsModelIgfem, i: usize) -> Result<(Real, Real)> {
    let get = |p: &str| -> Result<Real> {
        match model.smm.material(i)?.get_param(p)? {
            ParamValue::Real(v) => Ok(v),
            v => Err(akantu_core::Error::InvalidArgument(format!(
                "parameter {p} of law {i} is not a real: {v:?}"
            ))),
        }
    };
    Ok((get("lambda")?, get("mu")?))
}

/// Exact displacement at `x` (`alpha` from the interface conditions).
fn exact(x: &[Real], alpha: Real) -> [Real; 2] {
    let (dx, dy) = (x[0] - CENTRE[0], x[1] - CENTRE[1]);
    let r = (dx * dx + dy * dy).sqrt();
    if r == 0.0 {
        return [0.0, 0.0];
    }
    let ur = if r <= RADIUS {
        ((1. - R * R / (RADIUS * RADIUS)) * alpha + R * R / (RADIUS * RADIUS)) * r
    } else {
        (r - R * R / r) * alpha + R * R / r
    };
    [ur * dx / r, ur * dy / r]
}

/// Structured `n × n` triangulation of `[−HALF, HALF]²` (each square split
/// along its diagonal, counter-clockwise triangles).
fn structured(n: usize) -> (Vec<[Real; 2]>, Vec<[usize; 3]>) {
    let mut nodes = Vec::new();
    #[allow(clippy::cast_precision_loss)] // n ≤ a few thousand
    let fn_ = n as Real;
    for j in 0..=n {
        for i in 0..=n {
            #[allow(clippy::cast_precision_loss)] // i, j ≤ n
            let (fi, fj) = (i as Real, j as Real);
            nodes.push([
                -HALF + (2.0 * HALF) * fi / fn_,
                -HALF + (2.0 * HALF) * fj / fn_,
            ]);
        }
    }
    let id = |i: usize, j: usize| j * (n + 1) + i;
    let mut tris = Vec::new();
    for j in 0..n {
        for i in 0..n {
            let (a, b, c, d) = (id(i, j), id(i + 1, j), id(i + 1, j + 1), id(i, j + 1));
            tris.push([a, b, c]);
            tris.push([a, c, d]);
        }
    }
    (nodes, tris)
}

/// Barycentric coordinates of `x` in the triangle `p` (Cramer).
fn barycentric(p: [[Real; 2]; 3], x: [Real; 2]) -> [Real; 3] {
    let det = (p[1][0] - p[0][0]) * (p[2][1] - p[0][1]) - (p[2][0] - p[0][0]) * (p[1][1] - p[0][1]);
    let l1 =
        ((x[0] - p[0][0]) * (p[2][1] - p[0][1]) - (p[2][0] - p[0][0]) * (x[1] - p[0][1])) / det;
    let l2 =
        ((p[1][0] - p[0][0]) * (x[1] - p[0][1]) - (x[0] - p[0][0]) * (p[1][1] - p[0][1])) / det;
    [1.0 - l1 - l2, l1, l2]
}

/// The 7-point degree-5 triangle rule (barycentric coordinates, weight
/// relative to the area).
fn rule() -> Vec<([Real; 3], Real)> {
    let s15 = (15.0 as Real).sqrt();
    let (a1, a2) = ((6. - s15) / 21., (6. + s15) / 21.);
    let (w1, w2) = ((155. + s15) / 1200., (155. - s15) / 1200.);
    let mut rule = vec![([1. / 3., 1. / 3., 1. / 3.], 9. / 40.)];
    for (aa, w) in [(a1, w1), (a2, w2)] {
        let b = 1. - 2. * aa;
        rule.push(([aa, aa, b], w));
        rule.push(([aa, b, aa], w));
        rule.push(([b, aa, aa], w));
    }
    rule
}

/// Solve the problem on the `n × n` mesh and return its level.
///
/// # Errors
/// Any model, mesh-generation or solver error.
pub fn solve_level(n: usize) -> Result<Level> {
    let (nodes, tris) = structured(n);
    let mut mesh = Mesh::new(2, "plate")?;
    {
        let mut acc = MeshAccessor::new(&mut mesh);
        for p in &nodes {
            acc.push_node(p)?;
        }
        let mut conn = acc.connectivity_mut(ElementType::Triangle3, GhostType::NotGhost);
        for t in &tris {
            let mut c = [0 as Idx; 3];
            for (k, &v) in t.iter().enumerate() {
                c[k] = Idx::try_from(v).map_err(|_| {
                    akantu_core::Error::InvalidArgument(format!("node index {v} out of range"))
                })?;
            }
            conn.push_tuple(&c);
        }
    }
    let parser = Parser::parse_str(DAT, "material.dat")?;
    let mut model =
        SolidMechanicsModelIgfem::new(SharedMesh::new(mesh), Some(2), "inclusion", parser)?;
    model.set_material_selector(Box::new(InclusionSelector));
    model.init_full(&ModelOptions::new(AnalysisMethod::Static))?;
    model.register_geometry_object(
        vec![SkSphere::try_from_f64(
            [CENTRE[0], CENTRE[1], 0.0],
            RADIUS * RADIUS,
        )?],
        "gel",
    )?;
    model.update("gel")?;
    let ((l0, m0), (l1, m1)) = (lame(&model, 0)?, lame(&model, 1)?);
    let a = RADIUS;
    let alpha =
        (l1 + m1 + m0) * R * R / ((l0 + m0) * a * a + (l1 + m1) * (R * R - a * a) + m0 * R * R);
    {
        let pos = model.mesh().read()?.nodes().clone();
        let mut disp = model.smm.displacement()?.clone();
        let mut boun = model.smm.blocked_dofs()?.clone();
        for i in 0..nodes.len() {
            let x = pos.tuple(i);
            if (x[0].abs() - HALF).abs() < 1e-12 || (x[1].abs() - HALF).abs() < 1e-12 {
                boun.tuple_mut(i).copy_from_slice(&[true, true]);
                disp.tuple_mut(i).copy_from_slice(&exact(x, alpha));
            }
        }
        model.smm.displacement_mut()?.copy_from(&disp)?;
        model.smm.blocked_dofs_mut()?.copy_from(&boun)?;
    }
    {
        let nls = model.smm.solver.non_linear_solver_mut(None)?;
        nls.set_param("max_iterations", ParamValue::Int(4))?;
        nls.set_param("threshold", ParamValue::Real(1e-10))?;
    }
    model.smm.solve_step(None)?;

    let mesh_h = model.mesh().clone();
    let m = mesh_h.read()?;
    let u = model.smm.displacement()?;
    let eng = model.ctx.engine()?;
    let rule = rule();
    let (mut err, mut nrm) = (0.0, 0.0);
    let mut tri =
        |p: [[Real; 2]; 3], eval: &dyn Fn([Real; 2]) -> Result<[Real; 2]>| -> Result<()> {
            let area = 0.5
                * ((p[1][0] - p[0][0]) * (p[2][1] - p[0][1])
                    - (p[2][0] - p[0][0]) * (p[1][1] - p[0][1]));
            for (l, w) in &rule {
                let x = [
                    l[0] * p[0][0] + l[1] * p[1][0] + l[2] * p[2][0],
                    l[0] * p[0][1] + l[1] * p[1][1] + l[2] * p[2][1],
                ];
                let (uh, ue) = (eval(x)?, exact(&x, alpha));
                err += w * area * ((uh[0] - ue[0]).powi(2) + (uh[1] - ue[1]).powi(2));
                nrm += w * area * (ue[0].powi(2) + ue[1].powi(2));
            }
            Ok(())
        };
    for ty in [
        ElementType::Triangle3,
        ElementType::IgfemTriangle4,
        ElementType::IgfemTriangle5,
    ] {
        for e in 0..m.nb_element(ty, GhostType::NotGhost) {
            let el = Element::try_new(ty, e, GhostType::NotGhost)?;
            let x = m.extract_nodal_values_from_element(&m.nodes(), el)?;
            let ue = m.extract_nodal_values_from_element(&u, el)?;
            let p = |k: usize| [x[2 * k], x[2 * k + 1]];
            if ty == ElementType::Triangle3 {
                let pts = [p(0), p(1), p(2)];
                let eval = |q: [Real; 2]| -> Result<[Real; 2]> {
                    let l = barycentric(pts, q);
                    Ok([
                        l[0] * ue[0] + l[1] * ue[2] + l[2] * ue[4],
                        l[0] * ue[1] + l[1] * ue[3] + l[2] * ue[5],
                    ])
                };
                tri(pts, &eval)?;
                continue;
            }
            let eval = |q: [Real; 2]| -> Result<[Real; 2]> {
                let v = eng.interpolate(&m, &q, &ue, el)?;
                Ok([v[0], v[1]])
            };
            for s in 0..2 {
                let sc: Vec<usize> = akantu_igfem::element::sub_element_connectivity(ty, s)?
                    .iter()
                    .map(|&k| usize::from(k))
                    .collect();
                tri([p(sc[0]), p(sc[1]), p(sc[2])], &eval)?;
                if sc.len() == 4 {
                    tri([p(sc[0]), p(sc[2]), p(sc[3])], &eval)?;
                }
            }
        }
    }
    let counts = [
        m.nb_element(ElementType::Triangle3, GhostType::NotGhost),
        m.nb_element(ElementType::IgfemTriangle4, GhostType::NotGhost),
        m.nb_element(ElementType::IgfemTriangle5, GhostType::NotGhost),
    ];
    #[allow(clippy::cast_precision_loss)] // n ≤ a few thousand
    let h = 2.0 * HALF / n as Real;
    Ok(Level {
        n,
        h,
        l2: (err / nrm).sqrt(),
        counts,
    })
}

/// Levels n = 8, 16, …, ≤ `max_n`.
///
/// # Errors
/// See [`solve_level`].
pub fn convergence(max_n: usize) -> Result<Vec<Level>> {
    let mut levels = Vec::new();
    let mut n = 8;
    while n <= max_n {
        levels.push(solve_level(n)?);
        n *= 2;
    }
    Ok(levels)
}

#[allow(dead_code)] // entry point of the example; unused where a test includes this file
fn main() -> Result<()> {
    let max_n = match std::env::args().nth(1) {
        Some(s) => s.parse::<usize>().map_err(|e| {
            akantu_core::Error::InvalidArgument(format!("finest mesh size `{s}`: {e}"))
        })?,
        None => 64,
    };
    let levels = convergence(max_n)?;
    println!("n\tL2 error\t[tri3, tri4, tri5]\trate");
    for (i, l) in levels.iter().enumerate() {
        let r = if i == 0 {
            "-".to_string()
        } else {
            format!("{:.3}", rate(&levels[i - 1], l))
        };
        println!("{}\t{:.4e}\t{:?}\t{r}", l.n, l.l2, l.counts);
    }
    Ok(())
}
